//! Validation of a Postgres CDC source or table against the upstream database, for the
//! sources read by the native engine.
//!
//! It is the counterpart of `PostgresValidator` of the connector node, which validates the
//! sources read by the Debezium based engine, and it performs the same checks with the same
//! error messages:
//!
//! - the configuration of the upstream database (`wal_level`, replication slots),
//! - the privileges of the user,
//! - the publication, which is created or altered to cover the table if needed,
//! - for a table, its existence, primary key and column types.

use std::collections::{BTreeMap, HashMap, HashSet};

use anyhow::anyhow;
use risingwave_common::catalog::cdc_type_compatibility::cdc_source_column_type_compatible;
use risingwave_pb::catalog::table::CdcTableType as PbCdcTableType;
use risingwave_pb::connector_service::PbTableSchema;
use risingwave_pb::data::data_type::TypeName as PbTypeName;
use thiserror_ext::AsReport;
use tokio_postgres::Row;
use tokio_postgres::types::ToSql;

use super::protocol::quote_identifier;
use crate::connector_common::postgres::create_pg_client_from_properties;

const HOST_KEY: &str = "hostname";
const PORT_KEY: &str = "port";
const USER_KEY: &str = "username";
const PASSWORD_KEY: &str = "password";
const DB_NAME_KEY: &str = "database.name";
const TABLE_NAME_KEY: &str = "table.name";
const SCHEMA_NAME_KEY: &str = "schema.name";
const SLOT_NAME_KEY: &str = "slot.name";
const PUBLICATION_NAME_KEY: &str = "publication.name";
const PUBLICATION_CREATE_KEY: &str = "publication.create.enable";
const IS_AWS_RDS_KEY: &str = "postgres.is.aws.rds";
const TEST_ONLY_FORCE_RDS_KEY: &str = "test.only.force.rds";
const AWS_RDS_HOST: &str = "amazonaws.com";
/// The columns generated by RisingWave do not exist in the upstream table.
const INTERNAL_COLUMN_PREFIX: &str = "_rw_";

// The errors are formatted as the ones of the connector node, which are gRPC statuses.

fn invalid_argument(message: impl std::fmt::Display) -> anyhow::Error {
    anyhow!("INVALID_ARGUMENT: {}", message)
}

fn failed_precondition(message: impl std::fmt::Display) -> anyhow::Error {
    anyhow!("FAILED_PRECONDITION: {}", message)
}

fn internal_error(error: tokio_postgres::Error) -> anyhow::Error {
    match error.as_db_error() {
        Some(db_error) => anyhow!("INTERNAL: ERROR: {}", db_error.message()),
        None => anyhow!("INTERNAL: {}", error.as_report()),
    }
}

fn ensure_prop_exists<'a>(
    props: &'a BTreeMap<String, String>,
    name: &str,
) -> anyhow::Result<&'a str> {
    props.get(name).map(|v| v.as_str()).ok_or_else(|| {
        invalid_argument(format!(
            "'{}' is not found. Please check the WITH properties",
            name
        ))
    })
}

fn ensure_prop_not_blank<'a>(
    props: &'a BTreeMap<String, String>,
    name: &str,
) -> anyhow::Result<&'a str> {
    let value = ensure_prop_exists(props, name)?;
    if value.trim().is_empty() {
        return Err(invalid_argument(format!(
            "'{}' cannot be empty. Please check the WITH properties",
            name
        )));
    }
    Ok(value)
}

fn is_true(props: &BTreeMap<String, String>, name: &str) -> bool {
    props
        .get(name)
        .is_some_and(|v| v.eq_ignore_ascii_case("true"))
}

/// Validate a Postgres CDC source (`is_cdc_source_job`), or a table created from such a
/// source, whose properties then include the name of the upstream table.
pub async fn validate_postgres_source(
    props: &BTreeMap<String, String>,
    table_schema: &PbTableSchema,
    is_cdc_source_job: bool,
) -> anyhow::Result<()> {
    let host = ensure_prop_not_blank(props, HOST_KEY)?;
    ensure_prop_not_blank(props, PORT_KEY)?;
    let database = ensure_prop_not_blank(props, DB_NAME_KEY)?;
    let user = ensure_prop_not_blank(props, USER_KEY)?;
    ensure_prop_exists(props, PASSWORD_KEY)?;
    // the table name is given in the non-sharing mode
    let table = if is_cdc_source_job {
        props.get(TABLE_NAME_KEY).map(|v| v.as_str())
    } else {
        Some(ensure_prop_not_blank(props, TABLE_NAME_KEY)?)
    };
    let schema = ensure_prop_not_blank(props, SCHEMA_NAME_KEY)?;
    let slot = ensure_prop_not_blank(props, SLOT_NAME_KEY)?;
    let publication = ensure_prop_not_blank(props, PUBLICATION_NAME_KEY)?;
    let publication_auto_create =
        ensure_prop_not_blank(props, PUBLICATION_CREATE_KEY)?.eq_ignore_ascii_case("true");

    let client = create_pg_client_from_properties(props, None)
        .await
        .map_err(|e| anyhow!("Internal error: {}", e.as_report()))?;

    let validator = Validator {
        client,
        table_schema,
        is_cdc_source_job,
        // RDS does not grant the superuser and replication attributes, but dedicated roles.
        is_aws_rds: is_true(props, IS_AWS_RDS_KEY)
            || host.contains(AWS_RDS_HOST)
            || is_true(props, TEST_ONLY_FORCE_RDS_KEY),
        user,
        database,
        schema,
        table: table.unwrap_or_default(),
        slot,
        publication,
        publication_auto_create,
    };
    validator.validate_db_config().await?;
    let is_superuser = validator.validate_privileges().await?;
    // A shared source captures the changes of multiple tables, there is no schema to check.
    if !is_cdc_source_job {
        validator.validate_table_schema().await?;
    }
    // The connector node alters the publication before checking the schema of the table, and
    // so leaves the table in the publication when the table is rejected. Here the publication
    // is only touched once everything else is validated.
    validator.validate_publication(is_superuser).await
}

struct Validator<'a> {
    client: tokio_postgres::Client,
    table_schema: &'a PbTableSchema,
    is_cdc_source_job: bool,
    is_aws_rds: bool,
    user: &'a str,
    database: &'a str,
    schema: &'a str,
    /// Empty for a shared source.
    table: &'a str,
    slot: &'a str,
    publication: &'a str,
    publication_auto_create: bool,
}

impl Validator<'_> {
    async fn query(&self, sql: &str, params: &[&(dyn ToSql + Sync)]) -> anyhow::Result<Vec<Row>> {
        self.client.query(sql, params).await.map_err(internal_error)
    }

    /// Run a query that returns one boolean per row, and returns the one of the last row.
    async fn query_bool(
        &self,
        sql: &str,
        params: &[&(dyn ToSql + Sync)],
    ) -> anyhow::Result<Option<bool>> {
        let rows = self.query(sql, params).await?;
        Ok(rows
            .last()
            .map(|row| row.get::<_, Option<bool>>(0).unwrap_or(false)))
    }

    /// `"schema"."table"`, to be cast to `regclass`.
    fn qualified_table_name(&self, table: &str) -> String {
        format!("\"{}\".\"{}\"", self.schema, table)
    }

    fn column_names(&self) -> impl Iterator<Item = &str> {
        self.table_schema.columns.iter().map(|c| c.name.as_str())
    }

    fn primary_key_names(&self) -> Vec<&str> {
        self.table_schema
            .pk_indices
            .iter()
            .filter_map(|i| self.table_schema.columns.get(*i as usize))
            .map(|c| c.name.as_str())
            .collect()
    }

    async fn server_major_version(&self) -> anyhow::Result<i32> {
        let rows = self
            .query(
                "SELECT current_setting('server_version_num')::int4 / 10000",
                &[],
            )
            .await?;
        Ok(rows.first().map(|row| row.get(0)).unwrap_or_default())
    }

    /// Validate the configuration of the upstream database.
    async fn validate_db_config(&self) -> anyhow::Result<()> {
        // whether the logical decoding is enabled
        let rows = self
            .query("SELECT current_setting('wal_level')", &[])
            .await?;
        for row in rows {
            if row.get::<_, String>(0) != "logical" {
                return Err(invalid_argument(
                    "Postgres wal_level should be 'logical'.\nPlease modify the config and restart your Postgres server.",
                ));
            }
        }

        // whether the replication slot already exists
        let rows = self
            .query(
                "SELECT slot_name::text FROM pg_replication_slots WHERE slot_name = $1::text AND database = $2::text",
                &[&self.slot, &self.database],
            )
            .await?;
        if rows.is_empty() {
            // otherwise a new one will be created, check whether the limit is reached
            let full = self
                .query_bool(
                    "SELECT (SELECT count(*) FROM pg_replication_slots) = \
                     (SELECT setting FROM pg_settings WHERE name = 'max_replication_slots')::int",
                    &[],
                )
                .await?;
            if full == Some(true) {
                return Err(failed_precondition(
                    "all replication slots are in use\n Hint: Free one or increase max_replication_slots.",
                ));
            }
        } else {
            tracing::info!(slot = %self.slot, "replication slot already exists, just use it");
        }
        Ok(())
    }

    /// Validate the privileges required to read the changes and the tables. Returns whether
    /// the user is a superuser.
    async fn validate_privileges(&self) -> anyhow::Result<bool> {
        const NOT_REPLICATION_ROLE: &str =
            "Postgres user must be superuser or replication role to start walsender.";

        let mut is_superuser = false;
        if self.is_aws_rds {
            let rows = self
                .query(
                    "SELECT pg_has_role($1::text, 'rds_superuser', 'member'), \
                     pg_has_role($1::text, 'rds_replication', 'member')",
                    &[&self.user],
                )
                .await?;
            let mut has_replication_role = false;
            for row in rows {
                is_superuser = row.get::<_, Option<bool>>(0).unwrap_or(false);
                has_replication_role = row.get::<_, Option<bool>>(1).unwrap_or(false);
            }
            if !is_superuser && !has_replication_role {
                return Err(invalid_argument(NOT_REPLICATION_ROLE));
            }
        } else {
            is_superuser = self
                .query_bool(
                    "SELECT rolsuper FROM pg_roles WHERE rolname = $1::text",
                    &[&self.user],
                )
                .await?
                .unwrap_or(false);
            if !is_superuser {
                let rows = self
                    .query(
                        "SELECT rolreplication OR rolsuper FROM pg_roles WHERE rolname = $1::text",
                        &[&self.user],
                    )
                    .await?;
                for row in rows {
                    if !row.get::<_, Option<bool>>(0).unwrap_or(false) {
                        return Err(invalid_argument(NOT_REPLICATION_ROLE));
                    }
                }
            }
        }

        self.validate_table_privileges(is_superuser).await?;
        Ok(is_superuser)
    }

    /// The tables are read by the backfill.
    async fn validate_table_privileges(&self, is_superuser: bool) -> anyhow::Result<()> {
        if is_superuser || self.is_cdc_source_job {
            return Ok(());
        }
        let rows = self
            .query(
                "SELECT has_table_privilege($1::text, $2::text, 'SELECT')",
                &[&self.user, &self.qualified_table_name(self.table)],
            )
            .await?;
        for row in rows {
            if !row.get::<_, Option<bool>>(0).unwrap_or(false) {
                return Err(invalid_argument(format!(
                    "Postgres user must have select privilege on table '{}.{}'",
                    self.schema, self.table
                )));
            }
        }
        Ok(())
    }

    /// Check the publication, and create or alter it to cover the table if needed.
    async fn validate_publication(&self, is_superuser: bool) -> anyhow::Result<()> {
        let publication_exists = self
            .query_bool(
                "SELECT count(*) > 0 FROM pg_publication WHERE pubname = $1::text",
                &[&self.publication],
            )
            .await?
            .unwrap_or(false);

        if !publication_exists && !self.publication_auto_create {
            return Err(invalid_argument(format!(
                "Publication '{}' doesn't exist and auto create is disabled",
                self.publication
            )));
        }

        // The publication of a shared source is created without any table, the tables are
        // added when they are created from the source.
        if self.is_cdc_source_job {
            if !publication_exists {
                self.create_publication().await?;
            }
            return Ok(());
        }

        let pg_version = self.server_major_version().await?;

        // Since v15, a publication can cover a subset of the columns of a table.
        let is_partial_publication_enabled = self
            .query_bool(
                "SELECT count(*) > 0 FROM information_schema.columns \
                 WHERE table_name = 'pg_publication_tables' AND column_name = 'attnames'",
                &[],
            )
            .await?
            .unwrap_or(false);

        let partitions = self
            .query(
                "SELECT c.relname::text FROM pg_inherits AS i \
                 JOIN pg_class AS c ON i.inhrelid = c.oid \
                 JOIN pg_class AS p ON i.inhparent = p.oid \
                 JOIN pg_namespace AS n ON p.relnamespace = n.oid \
                 WHERE n.nspname = $1::text AND p.relname = $2::text",
                &[&self.schema, &self.table],
            )
            .await?;

        if !partitions.is_empty() && publication_exists {
            // `pubviaroot` is added in v13, before which a partitioned table cannot be added
            // to a publication, so the column exists if the table has partitions.
            let via_root = self
                .query(
                    "SELECT pubviaroot FROM pg_publication WHERE pubname = $1::text",
                    &[&self.publication],
                )
                .await?
                .first()
                .map(|row| row.get::<_, Option<bool>>(0).unwrap_or(false))
                .unwrap_or(false);
            if !via_root {
                return Err(invalid_argument(format!(
                    "Table '{table}' has partitions, which requires publication '{publication}' to be created with `publish_via_partition_root = true`. \nHint: you can run `SELECT pubviaroot from pg_publication WHERE pubname = '{publication}'` in the upstream Postgres to check.",
                    table = self.table,
                    publication = self.publication
                )));
            }
        }

        // Since v13, a partitioned table can be added to a publication. A table cannot be read
        // correctly from the slot if one of its ancestors or descendants is already in the
        // publication, so such a request is denied.
        if publication_exists && pg_version >= 13 {
            let mut family: Vec<String> = vec![];
            let mut current = self.table.to_owned();
            loop {
                let name = self.qualified_table_name(&current);
                let rows = self
                    .query(
                        "SELECT parentrelid::text FROM pg_partition_tree($1::text::regclass) \
                         WHERE relid = $1::text::regclass AND parentrelid <> $1::text::regclass",
                        &[&name],
                    )
                    .await?;
                match rows.first().and_then(|row| row.get::<_, Option<String>>(0)) {
                    Some(parent) => {
                        family.push(parent.clone());
                        current = parent;
                    }
                    None => break,
                }
            }
            let name = self.qualified_table_name(self.table);
            let rows = self
                .query(
                    "SELECT relid::text FROM pg_partition_tree($1::text::regclass) \
                     WHERE relid <> $1::text::regclass",
                    &[&name],
                )
                .await?;
            family.extend(rows.iter().map(|row| row.get::<_, String>(0)));

            for relative in &family {
                let covered = self
                    .query_bool(
                        "SELECT count(*) > 0 FROM pg_publication_tables \
                         WHERE schemaname = $1::text AND tablename = $2::text AND pubname = $3::text",
                        &[&self.schema, relative, &self.publication],
                    )
                    .await?
                    .unwrap_or(false);
                if covered {
                    return Err(invalid_argument(format!(
                        "The ancestor or descendant partition '{relative}' of the table partition '{table}' is already covered in the publication '{publication}'. Please use a new publication for '{table}'",
                        table = self.table,
                        publication = self.publication
                    )));
                }
            }
        }

        // The generated columns are not replicated, they are not expected in the publication.
        // The query fails before v12, which does not support the generated columns.
        let generated_columns: HashSet<String> = match self
            .client
            .query(
                "SELECT a.attname::text FROM pg_attribute a \
                 JOIN pg_class c ON a.attrelid = c.oid \
                 JOIN pg_namespace n ON c.relnamespace = n.oid \
                 WHERE n.nspname = $1::text AND c.relname = $2::text \
                 AND a.attnum > 0 AND NOT a.attisdropped AND a.attgenerated != ''",
                &[&self.schema, &self.table],
            )
            .await
        {
            Ok(rows) => rows.iter().map(|row| row.get(0)).collect(),
            Err(e) => {
                tracing::debug!(error = %e.as_report(), "failed to query generated columns");
                HashSet::new()
            }
        };

        let mut publication_covers_table = false;
        if is_partial_publication_enabled {
            let rows = self
                .query(
                    "SELECT attnames::text[] FROM pg_publication_tables \
                     WHERE schemaname = $1::text AND tablename = $2::text AND pubname = $3::text",
                    &[&self.schema, &self.table, &self.publication],
                )
                .await?;
            if let Some(row) = rows.first() {
                let published: Vec<String> =
                    row.get::<_, Option<Vec<String>>>(0).unwrap_or_default();
                for column in self.column_names() {
                    if generated_columns.contains(column) {
                        continue;
                    }
                    if !published.iter().any(|name| name == column) {
                        return Err(invalid_argument(format!(
                            "The publication '{}' does not cover all columns of the table '{}.{}'",
                            self.publication, self.schema, self.table
                        )));
                    }
                }
                publication_covers_table = true;
            }
        } else {
            publication_covers_table = self
                .query_bool(
                    "SELECT count(*) > 0 FROM pg_publication_tables \
                     WHERE schemaname = $1::text AND tablename = $2::text AND pubname = $3::text",
                    &[&self.schema, &self.table, &self.publication],
                )
                .await?
                .unwrap_or(false);
        }

        // The publication has to be altered to cover the table, which requires privileges.
        if !publication_covers_table {
            if !is_superuser {
                self.validate_publication_privileges().await?;
            }
            if publication_exists {
                let sql = format!(
                    "ALTER PUBLICATION {} ADD TABLE {}",
                    quote_identifier(self.publication),
                    self.qualified_table_name(self.table)
                );
                tracing::info!(sql, "altering the publication");
                self.client
                    .batch_execute(&sql)
                    .await
                    .map_err(internal_error)?;
            }
        }
        Ok(())
    }

    /// Check the privileges required to add the table to the publication.
    async fn validate_publication_privileges(&self) -> anyhow::Result<()> {
        let rows = self
            .query(
                "SELECT has_database_privilege($1::text, $2::text, 'create') \
                 FROM pg_roles WHERE rolname = $1::text",
                &[&self.user, &self.database],
            )
            .await?;
        for row in rows {
            if !row.get::<_, Option<bool>>(0).unwrap_or(false) {
                return Err(invalid_argument(format!(
                    "Postgres user must have create privilege on database '{}'",
                    self.database
                )));
            }
        }

        // The user must own the table, directly or through a group.
        let rows = self
            .query(
                "SELECT tableowner::text FROM pg_tables WHERE schemaname = $1::text AND tablename = $2::text",
                &[&self.schema, &self.table],
            )
            .await?;
        let table_owner = rows.last().and_then(|row| row.get::<_, Option<String>>(0));
        let mut is_table_owner = table_owner.as_deref() == Some(self.user);

        if !is_table_owner && let Some(table_owner) = &table_owner {
            let rows = self
                .query(
                    "WITH RECURSIVE base (g, m) AS (( \
                     SELECT r1.rolname AS group, ARRAY_AGG(DISTINCT(r2.rolname)) AS members FROM pg_auth_members am \
                     INNER JOIN pg_roles r1 ON r1.oid = am.roleid \
                     INNER JOIN pg_roles r2 ON r2.oid = am.member \
                     WHERE r1.rolname = $1::text \
                     GROUP BY r1.rolname \
                     ) \
                     UNION ALL ( \
                     WITH groups AS (SELECT DISTINCT(UNNEST(m)) AS g FROM base) \
                     SELECT r1.rolname AS group, ARRAY_AGG(DISTINCT(r2.rolname)) AS members FROM pg_auth_members am \
                     INNER JOIN pg_roles r1 ON r1.oid = am.roleid \
                     INNER JOIN pg_roles r2 ON r2.oid = am.member \
                     INNER JOIN groups ON r1.rolname = groups.g \
                     GROUP BY r1.rolname \
                     ) \
                     ), \
                     tmp AS (SELECT DISTINCT(UNNEST(m)) AS members FROM base) \
                     SELECT ARRAY_AGG(members)::text[] AS members FROM tmp",
                    &[table_owner],
                )
                .await?;
            is_table_owner = rows.iter().any(|row| {
                row.get::<_, Option<Vec<String>>>(0)
                    .is_some_and(|members| members.iter().any(|member| member == self.user))
            });
        }
        if !is_table_owner {
            return Err(invalid_argument(format!(
                "Postgres user must be the owner of table '{}' to create/alter publication",
                self.table
            )));
        }
        Ok(())
    }

    /// Create the publication. It is created with `publish_via_partition_root`, which is
    /// required to capture the partitioned tables and is supported since v13, before which a
    /// partitioned table cannot be added to a publication anyway.
    async fn create_publication(&self) -> anyhow::Result<()> {
        let with_clause = if self.server_major_version().await? >= 13 {
            " WITH ( publish_via_partition_root = true )"
        } else {
            ""
        };
        let sql = if self.table.trim().is_empty() {
            format!(
                "CREATE PUBLICATION {}{}",
                quote_identifier(self.publication),
                with_clause
            )
        } else {
            format!(
                "CREATE PUBLICATION {} FOR TABLE {}{}",
                quote_identifier(self.publication),
                self.qualified_table_name(self.table),
                with_clause
            )
        };
        tracing::info!(sql, "publication doesn't exist, creating it");
        self.client
            .batch_execute(&sql)
            .await
            .map_err(|e| anyhow!("Internal error: {}", e.as_report()))
    }

    /// Check that the table exists, and that its primary key and columns match the schema
    /// declared in RisingWave.
    async fn validate_table_schema(&self) -> anyhow::Result<()> {
        let exists = self
            .query_bool(
                "SELECT EXISTS (SELECT FROM pg_tables WHERE schemaname = $1::text AND tablename = $2::text)",
                &[&self.schema, &self.table],
            )
            .await?
            .unwrap_or(false);
        if !exists {
            return Err(invalid_argument("Postgres table or schema doesn't exist"));
        }

        // primary key
        let rows = self
            .query(
                "SELECT a.attname::text FROM pg_index i \
                 JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) \
                 WHERE i.indrelid = $1::text::regclass AND i.indisprimary",
                &[&self.qualified_table_name(self.table)],
            )
            .await?;
        let upstream_pk: HashSet<String> = rows.iter().map(|row| row.get(0)).collect();
        let pk = self.primary_key_names();
        if pk.len() != upstream_pk.len() {
            return Err(invalid_argument(format!(
                "Primary key mismatch: the SQL schema defines {} primary key columns, but the source table in Postgres has {} columns.",
                pk.len(),
                upstream_pk.len()
            )));
        }
        for column in pk {
            if !upstream_pk.contains(column) {
                return Err(invalid_argument(format!(
                    "Primary key mismatch: The primary key list of the source table in Postgres does not contain '{}'.\nHint: If your primary key contains uppercase letters, please ensure that the primary key in the DML of RisingWave uses the same uppercase format and is wrapped with double quotes (\"\").",
                    column
                )));
            }
        }

        // All the columns declared in RisingWave must exist in the upstream table with a
        // compatible type.
        struct UpstreamColumn {
            data_type: String,
            char_max_length: Option<i64>,
            udt_name: Option<String>,
            atttypmod: Option<i32>,
        }
        let rows = self
            .query(
                "SELECT c.column_name::text, c.data_type::text, c.character_maximum_length::int8, \
                 c.udt_name::text, a.atttypmod \
                 FROM information_schema.columns c \
                 JOIN pg_catalog.pg_namespace n ON n.nspname = c.table_schema \
                 JOIN pg_catalog.pg_class cls ON cls.relname = c.table_name AND cls.relnamespace = n.oid \
                 JOIN pg_catalog.pg_attribute a ON a.attrelid = cls.oid AND a.attname = c.column_name \
                 WHERE c.table_schema = $1::text AND c.table_name = $2::text \
                 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY c.ordinal_position",
                &[&self.schema, &self.table],
            )
            .await?;
        let upstream_columns: HashMap<String, UpstreamColumn> = rows
            .iter()
            .map(|row| {
                (
                    row.get::<_, String>(0),
                    UpstreamColumn {
                        data_type: row.get::<_, Option<String>>(1).unwrap_or_default(),
                        char_max_length: row.get(2),
                        udt_name: row.get(3),
                        atttypmod: row.get(4),
                    },
                )
            })
            .collect();

        for column in &self.table_schema.columns {
            let name = column.name.as_str();
            if name.starts_with(INTERNAL_COLUMN_PREFIX) {
                continue;
            }
            let Some(upstream) = upstream_columns.get(name) else {
                return Err(invalid_argument(format!(
                    "Column '{}' not found in the upstream database",
                    name
                )));
            };
            let data_type = column.column_type.as_ref();
            let type_name = data_type
                .and_then(|t| PbTypeName::try_from(t.type_name).ok())
                .unwrap_or(PbTypeName::TypeUnspecified);
            if !cdc_source_column_type_compatible(
                PbCdcTableType::Postgres,
                &upstream.data_type,
                type_name,
                upstream.char_max_length,
                false,
                upstream.udt_name.as_deref(),
            ) {
                return Err(invalid_argument(format!(
                    "Incompatible data type of column {}",
                    name
                )));
            }

            // The dimension of a pgvector column is its type modifier, -1 if not specified.
            if type_name == PbTypeName::Vector
                && upstream
                    .udt_name
                    .as_deref()
                    .is_some_and(|udt| udt.eq_ignore_ascii_case("vector"))
            {
                let expected = data_type.map(|t| t.precision).unwrap_or_default();
                match upstream.atttypmod.filter(|dim| *dim > 0) {
                    None => {
                        return Err(invalid_argument(format!(
                            "Incompatible vector dimension of column {}: upstream vector has no dimension, but expected vector({})",
                            name, expected
                        )));
                    }
                    Some(dim) if dim as i64 != expected as i64 => {
                        return Err(invalid_argument(format!(
                            "Incompatible vector dimension of column {}: upstream vector({}), but expected vector({})",
                            name, dim, expected
                        )));
                    }
                    Some(_) => {}
                }
            }
        }
        Ok(())
    }
}
