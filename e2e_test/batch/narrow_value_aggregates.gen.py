"""Generates `e2e_test/batch/narrow_value_aggregates.slt`, the differential test of
`batch_narrow_value_aggregates` (rules `NarrowValueAggRule` and `NarrowValuePushRule`: the
functions that read the result of `first_value` / `last_value` are aggregated instead of the whole
value, and moved into the branches of a union and the side of a join that the value comes from).
Every query runs twice, with and without the variable, through `INSERT ... SELECT` (the batch
plan), and both results must hold the same rows with the same multiplicities, after each round of
changes of the data. The queries, the data and the rounds are those of the streaming test,
`e2e_test/streaming/narrow_value_aggregates.gen.py`.

Usage: python3 e2e_test/batch/narrow_value_aggregates.gen.py e2e_test/batch/narrow_value_aggregates.slt
"""
import importlib.util
import os
import sys

_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'streaming',
                     'narrow_value_aggregates.gen.py')
_spec = importlib.util.spec_from_file_location('narrow_value_aggregates_streaming', _path)
s = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(s)

VAR = 'batch_narrow_value_aggregates'
P = s.P


def run_all(title):
    s.out.append(f"# {title}: every query runs without, then with the variable.\n")
    for name, _, sql in s.CASES + [s.TIE_CASE]:
        s.stmt(f"delete from {P}_{name}_off")
        s.stmt(f"delete from {P}_{name}_on")
        s.stmt(f"insert into {P}_{name}_off {sql}")
        s.stmt(f"set {VAR} = true")
        s.stmt(f"insert into {P}_{name}_on {sql}")
        s.stmt(f"set {VAR} = false")
    s.out.append(f"# {title}: both results hold the same rows, each the same number of times.\n")
    for name, cols, _ in s.CASES:
        s.same_rows(f"{P}_{name}_on", f"{P}_{name}_off", cols)
    # The row picked among tied ones may differ from one run to the next: each result is checked
    # on its own.
    s.out.append("# Ties: in each result, all the fields come from one of the last rows.\n")
    name = s.TIE_CASE[0]
    for sfx in ('off', 'on'):
        s.tie_checks(f"{P}_{name}_{sfx}")


s.comment("""# Differential test of `batch_narrow_value_aggregates`: every query runs through
# `INSERT ... SELECT` without, then with the variable, and both results must hold the same rows
# with the same multiplicities, after each round of changes of the data.
#
# Generated by `python3 e2e_test/batch/narrow_value_aggregates.gen.py <this file>` (queries and
# data from `e2e_test/streaming/narrow_value_aggregates.gen.py`): edit them there and regenerate
# rather than editing by hand.
""")
s.setup()
for name, cols, _ in s.CASES + [s.TIE_CASE]:
    s.stmt(f"create table {P}_{name}_off ({cols})")
    s.stmt(f"create table {P}_{name}_on ({cols})")
s.scenario(run_all)
s.out.append("# Cleanup.\n")
for name, _, _ in reversed(s.CASES + [s.TIE_CASE]):
    s.stmt(f"drop table {P}_{name}_on")
    s.stmt(f"drop table {P}_{name}_off")
s.drop_inputs()

open(sys.argv[1], 'w').write("\n".join(s.out))
print(len(s.CASES) + 1, 'cases,', sum(1 for o in s.out if o.startswith(('statement', 'query'))), 'records')
