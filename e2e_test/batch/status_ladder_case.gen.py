"""Generates `e2e_test/batch/status_ladder_case.slt`, the differential test of the status ladder
picked with one `CASE` in batch plans (`batch_status_ladder_case`).

The queries, the tables and their changes are those of
`e2e_test/streaming/status_ladder_case.gen.py`. Every query is run as a batch query with and
without the variable (`INSERT ... SELECT` into a result table per query and setting), and both
result tables must hold the same multiset of rows, on the initial rows and after each round of
changes.

Usage: python3 e2e_test/batch/status_ladder_case.gen.py e2e_test/batch/status_ladder_case.slt
"""
import importlib.util
import os
import sys

sys.dont_write_bytecode = True
_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'streaming',
                     'status_ladder_case.gen.py')
_spec = importlib.util.spec_from_file_location('streaming_status_ladder_case', _path)
ladder = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ladder)

HEADER = """# Differential test of `batch_status_ladder_case`: every query is run as a batch query with and
# without the variable, into a result table each, and both must hold the same multiset of rows, on
# the initial rows and after each round of changes.
#
# Generated by `python3 e2e_test/batch/status_ladder_case.gen.py <this file>`: edit the list of
# queries in `e2e_test/streaming/status_ladder_case.gen.py` and regenerate rather than editing by
# hand.
"""

COLUMNS = ['c1 int', 'c2 varchar', 'c3 int']


def main():
    E, F, G = 'slb_e', 'slb_f', 'slb_g'
    queries = ladder.cases(E, F, G)
    slt = ladder.Slt()

    def run_and_compare(title):
        slt.comment(f"{title}: the query with and without the variable gives the same rows.")
        for name, _, width, sql in queries:
            for setting in ('off', 'on'):
                slt.stmt(f"delete from slb_r_{name}_{setting}")
            for setting in ('off', 'on'):
                slt.stmt(f"set batch_status_ladder_case = {'true' if setting == 'on' else 'false'}")
                slt.stmt(f"insert into slb_r_{name}_{setting} select * from ({sql}) q")
            slt.stmt("set batch_status_ladder_case = false")
            slt.same_multiset(f"slb_r_{name}_on", f"slb_r_{name}_off", width)

    slt.out.append(HEADER)
    slt.stmt("SET RW_IMPLICIT_FLUSH TO true")
    for table in ladder.TABLES:
        slt.stmt(table.format(E=E, F=F, G=G))
    for name, comment, width, _ in queries:
        slt.comment(comment)
        for setting in ('off', 'on'):
            slt.stmt(f"create table slb_r_{name}_{setting} ({', '.join(COLUMNS[:width])})")
    for sql in ladder.initial_rows(E, F, G):
        slt.stmt(sql)
    run_and_compare("On the initial rows")

    slt.comment("Spot checks of the rows themselves.")
    slt.query('IT', "select c1, c2 from slb_r_form1_on order by c1, c2",
              ["1 held", "2 closed", "3 held", "4 active", "5 closed", "6 active", "7 held", "NULL held"])
    slt.query('IT', "select c1, c2 from slb_r_unique_default_on order by c1",
              ["1 closed", "2 new", "3 new", "4 active", "5 closed", "6 new"])

    for title, statements in ladder.rounds(E, F, G):
        slt.comment(f"Changes: {title}.")
        for sql in statements:
            slt.stmt(sql)
        run_and_compare(f"After the changes ({title})")

    slt.comment("Cleanup.")
    for name, _, _, _ in reversed(queries):
        for setting in ('on', 'off'):
            slt.stmt(f"drop table slb_r_{name}_{setting}")
    for table in (G, F, E):
        slt.stmt(f"drop table {table}")
    slt.write(sys.argv[1])


if __name__ == '__main__':
    main()
