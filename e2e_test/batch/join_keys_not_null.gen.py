"""Generates `e2e_test/batch/join_keys_not_null.slt`, the differential test of
`batch_join_keys_not_null` (rule `JoinKeyNotNullRule`: `IS NOT NULL` filters on the columns that a
join compares with `=`, on the sides whose rows without a match are not output). Every query runs
twice, with and without the variable, through `INSERT ... SELECT` (the batch plan), and both
results must hold the same rows with the same multiplicities, after each round of changes of the
data.

Usage: python3 e2e_test/batch/join_keys_not_null.gen.py e2e_test/batch/join_keys_not_null.slt
"""
import sys

A, B, C = 'jkn_a', 'jkn_b', 'jkn_c'
P = 'jkn'
VAR = 'batch_join_keys_not_null'
SETTINGS = []

# (name, columns of the result, query)
CASES = [
    ('inner', 'aid int, bid int, k int',
     f"select a.id, b.id, a.k from {A} a join {B} b on a.k = b.k"),
    ('inner_not_null_col', 'aid int, cid int',
     f"select a.id, c.id from {A} a join {C} c on a.k = c.k"),
    ('inner_filtered', 'aid int, bid int',
     f"select a.id, b.id from {A} a join {B} b on a.k = b.k where a.k > 1"),
    ('left', 'aid int, bid int, w int',
     f"select a.id, b.id, b.w from {A} a left join {B} b on a.k = b.k"),
    ('right', 'aid int, bid int, v int',
     f"select a.id, b.id, a.v from {A} a right join {B} b on a.k = b.k"),
    ('full', 'aid int, bid int',
     f"select a.id, b.id from {A} a full join {B} b on a.k = b.k"),
    ('semi', 'aid int, k int',
     f"select a.id, a.k from {A} a where a.k in (select b.k from {B} b)"),
    ('anti', 'aid int, k int',
     f"select a.id, a.k from {A} a where not exists (select 1 from {B} b where b.k = a.k)"),
    ('not_in', 'aid int',
     f"select a.id from {A} a where a.k not in (select b.k from {B} b where b.k is not null)"),
    ('indf', 'aid int, bid int',
     f"select a.id, b.id from {A} a join {B} b on a.k is not distinct from b.k"),
    ('lookup', 'aid int, bid int, w int',
     f"select a.id, b.id, b.w from {A} a join {B} b on a.k = b.id"),
    ('expr', 'aid int, bid int',
     f"select a.id, b.id from {A} a join {B} b on a.k + 1 = b.k"),
    ('two_keys', 'aid int, bid int',
     f"select a.id, b.id from {A} a join {B} b on a.k = b.k and a.v = b.w"),
    ('three_way', 'aid int, bid int, cid int',
     f"select a.id, b.id, c.id from {A} a join {B} b on a.k = b.k join {C} c on c.w = b.w"),
    ('left_extra', 'aid int, bid int',
     f"select a.id, b.id from {A} a left join {B} b on a.k = b.k and b.w > a.v"),
    ('agg', 'k int, n bigint',
     f"select a.k, count(*) from {A} a join {B} b on a.k = b.k group by a.k"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def columns(cols):
    return ', '.join(col.split()[0] for col in cols.split(', '))


def run_all(title):
    out.append("sleep 5s\n")
    out.append(f"# {title}: every query runs without, then with the variable.\n")
    for name, _, sql in CASES:
        stmt(f"delete from {P}_{name}_off")
        stmt(f"delete from {P}_{name}_on")
        stmt(f"insert into {P}_{name}_off {sql}")
        stmt(f"set {VAR} = true")
        stmt(f"insert into {P}_{name}_on {sql}")
        stmt(f"set {VAR} = false")
    out.append(f"# {title}: both results hold the same rows, each the same number of times.\n")
    for name, cols, _ in CASES:
        a, b, c = f"{P}_{name}_on", f"{P}_{name}_off", columns(cols)
        grouped = lambda t: f"select {c}, count(*) as {P}_rows from {t} group by {c}"
        query('III',
              f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
              f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
              f"  (select count(*) from {a}) - (select count(*) from {b})",
              ["0 0 0"])


out.append(f"""# Differential test of `{VAR}`: every query runs through `INSERT ... SELECT` without, then
# with the variable, and both results must hold the same rows with the same multiplicities, after
# each round of changes of the data.
#
# Generated by `python3 e2e_test/batch/join_keys_not_null.gen.py <this file>`: edit the list of
# queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {A} (id int primary key, k int, v int)")
stmt(f"create table {B} (id int primary key, k int, w int)")
stmt(f"create table {C} (id int primary key, k int not null, w int)")
for name, cols, _ in CASES:
    stmt(f"create table {P}_{name}_off ({cols})")
    stmt(f"create table {P}_{name}_on ({cols})")

run_all("Empty tables")

out.append("# First data: NULL keys on both sides, duplicates, rows without a match.\n")
stmt(f"insert into {A} values (1, 1, 1), (2, 1, null), (3, null, 2), (4, null, null), (5, 2, 7), "
     f"(6, 0, 3), (7, 9, 1), (8, 3, 3)")
stmt(f"insert into {B} values (1, 1, 1), (2, 1, 2), (3, null, 2), (4, null, null), (5, 0, 3), "
     f"(6, 2, null), (7, 4, 7), (9, 3, 3)")
stmt(f"insert into {C} values (1, 1, 1), (2, 2, 2), (3, 0, null), (4, 9, 7)")
run_all("First data")

query('I', f"select count(*) from {P}_anti_on", ["3"])
query('I', f"select count(*) from {P}_left_on", ["10"])

out.append("# Second data: keys set to NULL and back, more rows.\n")
stmt(f"update {A} set k = null where id in (1, 5)")
stmt(f"update {A} set k = 4 where id = 3")
stmt(f"update {B} set k = null where id = 2")
stmt(f"insert into {A} select i, i % 6, i % 4 from generate_series(10, 60) as s(i)")
stmt(f"insert into {B} select i, case when i % 7 = 0 then null else i % 5 end, i % 3 "
     f"from generate_series(10, 40) as s(i)")
run_all("Second data")

out.append("# Third data: only NULL keys on one side, then deletes.\n")
stmt(f"update {B} set k = null")
run_all("Only NULL keys on the right side")
stmt(f"delete from {B}")
stmt(f"delete from {A} where k is not null")
run_all("Empty right side")

out.append("# Cleanup.\n")
for name, _, _ in reversed(CASES):
    stmt(f"drop table {P}_{name}_on")
    stmt(f"drop table {P}_{name}_off")
for table in (C, B, A):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
