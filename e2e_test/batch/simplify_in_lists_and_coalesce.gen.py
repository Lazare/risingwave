"""Generates `e2e_test/batch/simplify_in_lists_and_coalesce.slt`, the differential test of
`batch_simplify_in_lists_and_coalesce` (rule `InListCoalesceSimplifyRule`: the conjuncts that restrict
the same expression to lists of constants are intersected, the repeated arguments of `COALESCE`
are removed). Every query runs twice, with and without the variable, through `INSERT ... SELECT` (the
batch plan), and both results must hold the same rows with the same multiplicities, after each
round of changes of the data.

Usage: python3 e2e_test/batch/simplify_in_lists_and_coalesce.gen.py e2e_test/batch/simplify_in_lists_and_coalesce.slt
"""
import sys

T, R = 'sil_t', 'sil_r'
VAR = 'batch_simplify_in_lists_and_coalesce'
P = 'sil'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule.
    ('one_common', 'id int',
     f"select id from {T} where c in (1, 2) and c in (1, 3, 4)"),
    ('two_common', 'id int',
     f"select id from {T} where a in ('x', 'y', 'z') and a in ('w', 'z', 'y')"),
    ('equality', 'id int',
     f"select id from {T} where c = 2 and c in (1, 2) and d > 0"),
    ('null_item', 'id int',
     f"select id from {T} where c in (1, null) and c in (1, 2)"),
    ('expression', 'id int',
     f"select id from {T} where upper(a) in ('X', 'Y') and upper(a) in ('Y', 'Z')"),
    ('empty', 'id int',
     f"select id from {T} where upper(a) in ('X', 'Y') and upper(a) in ('Z')"),
    ('empty_join', 'n bigint',
     f"select count(*) as n from {T} t join {R} r on t.c = r.v where t.c in (1, 2) and t.c in (3)"),
    ('join_condition', 'id int, k varchar',
     f"select t.id, r.k from {T} t left join {R} r on t.c = r.v and r.k in ('x', 'y') and r.k in ('y', 'z')"),
    ('coalesce_project', 'x varchar, y int',
     f"select coalesce(a, a, b, a) as x, coalesce(c, c) as y from {T}"),
    ('coalesce_filter', 'id int',
     f"select id from {T} where coalesce(a, b, a, b) = 'x'"),
    ('coalesce_group', 'x varchar, n bigint',
     f"select coalesce(b, b, a) as x, count(*) as n from {T} group by coalesce(b, b, a)"),
    # Left as they are by the rule.
    ('kept_different_columns', 'id int',
     f"select id from {T} where c in (1, 2) and d in (2, 3)"),
    ('kept_or', 'id int',
     f"select id from {T} where c in (1, 2) or c in (2, 3)"),
    ('kept_numeric', 'id int',
     f"select id from {T} where n in (1.0, 2.0) and n in (1.00, 3.0)"),
    ('kept_not_in', 'id int',
     f"select id from {T} where c not in (1, 2) and c in (2, 3)"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def columns(cols):
    return ', '.join(col.split()[0] for col in cols.split(', '))


def run_all(title):
    out.append(f"# {title}: every query runs without, then with the variable.\n")
    for name, _, sql in CASES:
        stmt(f"delete from {P}_{name}_off")
        stmt(f"delete from {P}_{name}_on")
        stmt(f"insert into {P}_{name}_off {sql}")
        stmt(f"set {VAR} = true")
        stmt(f"insert into {P}_{name}_on {sql}")
        stmt(f"set {VAR} = false")
    out.append(f"# {title}: both results hold the same rows, each the same number of times.\n")
    for name, cols, _ in CASES:
        a, b, c = f"{P}_{name}_on", f"{P}_{name}_off", columns(cols)
        grouped = lambda t: f"select {c}, count(*) as {P}_rows from {t} group by {c}"
        query('III',
              f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
              f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
              f"  (select count(*) from {a}) - (select count(*) from {b})",
              ["0 0 0"])


out.append("""# Differential test of `batch_simplify_in_lists_and_coalesce`: every query runs through
# `INSERT ... SELECT` without, then with the variable, and both results must hold the same rows
# with the same multiplicities, after each round of changes of the data.
#
# Generated by `python3 e2e_test/batch/simplify_in_lists_and_coalesce.gen.py <this file>`: edit the list
# of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {T} (id int primary key, a varchar, b varchar, c int, d int, n numeric)")
stmt(f"create table {R} (id int primary key, k varchar, v int)")
for name, cols, _ in CASES:
    stmt(f"create table {P}_{name}_off ({cols})")
    stmt(f"create table {P}_{name}_on ({cols})")

run_all("Empty tables")

out.append("# First data: NULLs, duplicates, values in one list, in both lists, in none.\n")
stmt(f"insert into {T} values (1, 'x', null, 1, 2, 1.0), (2, null, 'y', 2, 1, 1.00), (3, 'y', 'x', 3, null, 3), "
     f"(4, 'Y', null, null, 3, null), (5, null, null, 1, 0, 2.0), (6, 'z', 'z', 2, 2, 2), (7, 'x', 'x', 4, 1, 1)")
stmt(f"insert into {R} values (1, 'x', 1), (2, 'y', 2), (3, 'z', 3), (4, null, 1), (5, 'y', null)")
run_all("First data")

query('I', f"select count(*) from {P}_one_common_on", ["2"])
query('I', f"select count(*) from {P}_empty_on", ["0"])

out.append("# Second data: more rows, rows written again with an existing primary key.\n")
stmt(f"insert into {T} values (8, 'Z', 'y', 1, 5, 1.000), (1, 'y', 'y', 2, 2, 2.0)")
stmt(f"insert into {R} values (6, 'y', 2), (1, 'z', 1)")
run_all("Second data")

out.append("# Third data: values set to NULL and back, deletes.\n")
stmt(f"update {T} set c = null, a = null where id in (2, 6)")
stmt(f"update {T} set c = 1 where id = 4")
stmt(f"delete from {T} where id = 7")
stmt(f"delete from {R} where id in (2, 3)")
run_all("Third data")

out.append("# Fourth data: an empty table on one side.\n")
stmt(f"delete from {R}")
run_all("Empty right side")
stmt(f"delete from {T}")
run_all("Empty tables again")

out.append("# Cleanup.\n")
for name, _, _ in reversed(CASES):
    stmt(f"drop table {P}_{name}_on")
    stmt(f"drop table {P}_{name}_off")
for table in (R, T):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
