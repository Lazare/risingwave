"""Generates `e2e_test/batch/broadcast_cross_join.slt`, the differential test of
`batch_broadcast_cross_join` (rule `ConstantKeyJoinRule` and `BatchNestedLoopJoin`: a cross join,
or a join on the same constant on both sides, runs as a nested loop join that copies its left side
to every task of its right side). Every query runs twice in the distributed mode, with and without
the variable, through `INSERT ... SELECT`, and both results must hold the same rows with the same
multiplicities, after each round of changes of the data.

Usage: python3 e2e_test/batch/broadcast_cross_join.gen.py e2e_test/batch/broadcast_cross_join.slt
"""
import sys

T, C, TV, CV = 'bcj_t', 'bcj_c', 'bcj_tv', 'bcj_cv'
VAR = 'batch_broadcast_cross_join'
P = 'bcj'

# (name, columns of the result, query)
CASES = [
    # Rewritten.
    ('constant_key', 'id int, cid varchar',
     f"select {TV}.id, {CV}.cid from {TV} join {CV} on {TV}.one = {CV}.one"),
    ('constant_key_and_column', 'id int, cid varchar',
     f"select {TV}.id, {CV}.cid from {TV} join {CV} on {TV}.one = {CV}.one and {TV}.v = {CV}.rate"),
    ('cross', 'id int, cid varchar',
     f"select {T}.id, {C}.id as cid from {T} cross join {C}"),
    ('non_equi', 'id int, cid varchar',
     f"select {T}.id, {C}.id as cid from {T} join {C} on {T}.v > {C}.rate"),
    ('cross_agg', 'cid varchar, n bigint, s bigint',
     f"select {C}.id as cid, count(*) as n, sum({T}.v) as s from {T} cross join {C} group by {C}.id"),
    ('constant_key_filtered', 'id int, cid varchar, rate int',
     f"select {TV}.id, {CV}.cid, {CV}.rate from {TV} join {CV} on {TV}.one = {CV}.one "
     f"where {TV}.x % 7 = 0 and {CV}.rate is not null"),
    ('right_join', 'id int, cid varchar',
     f"select {T}.id, {C}.id as cid from {T} right join {C} on {T}.v = {C}.rate + {T}.x * 0 + 1000"),
    ('semi_non_equi', 'id varchar',
     f"select id from {C} where exists (select 1 from {T} where {T}.v > {C}.rate * 10)"),
    ('anti_non_equi', 'id varchar',
     f"select id from {C} where not exists (select 1 from {T} where {T}.v < {C}.rate)"),
    # Left as they are.
    ('kept_left', 'id int, cid varchar',
     f"select {T}.id, {C}.id as cid from {T} left join {C} on {T}.v > {C}.rate + 90"),
    ('kept_full', 'id int, cid varchar',
     f"select {T}.id, {C}.id as cid from {T} full join {C} on {T}.v > {C}.rate + 90"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def columns(cols):
    return ', '.join(col.split()[0] for col in cols.split(', '))


def run_all(title):
    out.append(f"# {title}: every query runs without, then with the variable.\n")
    for name, _, sql in CASES:
        stmt(f"delete from {P}_{name}_off")
        stmt(f"delete from {P}_{name}_on")
        stmt(f"insert into {P}_{name}_off {sql}")
        stmt(f"set {VAR} = true")
        stmt(f"insert into {P}_{name}_on {sql}")
        stmt(f"set {VAR} = false")
    out.append(f"# {title}: both results hold the same rows, each the same number of times.\n")
    for name, cols, _ in CASES:
        a, b, c = f"{P}_{name}_on", f"{P}_{name}_off", columns(cols)
        grouped = lambda t: f"select {c}, count(*) as {P}_rows from {t} group by {c}"
        query('III',
              f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
              f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
              f"  (select count(*) from {a}) - (select count(*) from {b})",
              ["0 0 0"])


out.append("""# Differential test of `batch_broadcast_cross_join`: every query runs through
# `INSERT ... SELECT` in the distributed mode without, then with the variable, and both results
# must hold the same rows with the same multiplicities, after each round of changes of the data.
#
# Generated by `python3 e2e_test/batch/broadcast_cross_join.gen.py <this file>`: edit the list
# of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt("set query_mode = distributed")
stmt(f"create table {T} (id int primary key, v int, x int)")
stmt(f"create table {C} (id varchar primary key, rate int)")
stmt(f"create view {TV} as select id, v, x, 1 as one from {T}")
stmt(f"create view {CV} as select id as cid, rate, 1 as one from {C}")
for name, cols, _ in CASES:
    stmt(f"create table {P}_{name}_off ({cols})")
    stmt(f"create table {P}_{name}_on ({cols})")

run_all("Empty tables")

out.append("# First data: a few hundred rows on one side, a few rows with NULLs on the other.\n")
stmt(f"insert into {T} select i, i % 100, i from generate_series(1, 300) as s(i)")
stmt(f"insert into {T} values (301, null, null), (302, null, 5)")
stmt(f"insert into {C} values ('a', 10), ('b', 50), ('c', null), ('d', 99), ('e', 10)")
run_all("First data")

query('I', f"select count(*) from {P}_cross_on", ["1510"])
query('I', f"select count(*) from {P}_constant_key_on", ["1510"])

out.append("# Second data: more rows, rows written again with an existing primary key.\n")
stmt(f"insert into {T} select i, i % 13, i * 2 from generate_series(250, 400) as s(i)")
stmt(f"insert into {C} values ('f', -1), ('a', 20)")
run_all("Second data")

out.append("# Third data: deletes, then only one row on the small side.\n")
stmt(f"delete from {T} where id % 3 = 0")
stmt(f"delete from {C} where id <> 'b'")
run_all("One row on the small side")

out.append("# Fourth data: an empty side.\n")
stmt(f"delete from {C}")
run_all("Empty small side")
stmt(f"insert into {C} values ('a', 1)")
stmt(f"delete from {T}")
run_all("Empty large side")

out.append("# Cleanup.\n")
for name, _, _ in reversed(CASES):
    stmt(f"drop table {P}_{name}_on")
    stmt(f"drop table {P}_{name}_off")
stmt(f"drop view {CV}")
stmt(f"drop view {TV}")
for table in (C, T):
    stmt(f"drop table {table}")
stmt("set query_mode = auto")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
