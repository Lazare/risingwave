"""Generates `e2e_test/batch/scan_read_memory.slt`, the end-to-end test of the memory of the storage
reads of batch scans: full scans of a table with wide JSON rows (about 3 KB each), several scans
running at once in one query (UNION ALL, self join), with each scan variable off and on, alone and
together, in the distributed and local query modes. The results must not change; the expected
values are computed here, from the same data.

Variables: `batch_scan_max_open_vnode_iterators`, `batch_scan_prefetch_budget_mb`,
`batch_scan_prefetch_within_query_limit`, `batch_scan_release_prefetch_after_ms`.

Usage: python3 e2e_test/batch/scan_read_memory.gen.py e2e_test/batch/scan_read_memory.slt
"""
import hashlib
import sys

N = 30000
T = 'srm_t'
REPEAT = 90  # 32 hexadecimal digits x 90 = 2880 bytes of padding per row

VARIANTS = [
    ('defaults', []),
    ('one vnode iterator at a time', [('batch_scan_max_open_vnode_iterators', '1')]),
    ('eight vnode iterators at a time', [('batch_scan_max_open_vnode_iterators', '8')]),
    ('a prefetch budget of 1 MB per scan', [('batch_scan_prefetch_budget_mb', '1')]),
    ('no prefetch beyond the limit of the query',
     [('batch_scan_prefetch_within_query_limit', 'true')]),
    ('prefetched blocks dropped after 1 ms of held back output',
     [('batch_scan_release_prefetch_after_ms', '1')]),
    ('all together', [
        ('batch_scan_max_open_vnode_iterators', '4'),
        ('batch_scan_prefetch_budget_mb', '1'),
        ('batch_scan_prefetch_within_query_limit', 'true'),
        ('batch_scan_release_prefetch_after_ms', '1'),
    ]),
]
DEFAULTS = [
    ('batch_scan_max_open_vnode_iterators', '0'),
    ('batch_scan_prefetch_budget_mb', '0'),
    ('batch_scan_prefetch_within_query_limit', 'false'),
    ('batch_scan_release_prefetch_after_ms', '0'),
]


def md5(i):
    return hashlib.md5(str(i).encode()).hexdigest()


def queries(rows):
    """(sql, sort mode, expected rows) for the current `rows`: {id: pad}."""
    ids = sorted(rows)
    full = sum(1 for i in ids if rows[i] == md5(i) * REPEAT)
    a = [(len(ids), sum(ids), sum(len(rows[i]) for i in ids), full)]
    union = [i for i in ids] + [i for i in ids if i % 2 == 0] + [i for i in ids if i % 3 == 0]
    b = [(len(union), sum(union))]
    pairs = [i for i in ids if (i - 1) in rows and rows[i] != rows[i - 1]]
    c = [(len(pairs), sum(pairs))]
    d = [(i,) for i in ids[:3]]
    return [
        (f"SELECT count(*), sum(id), sum(length(v->>'pad')), "
         f"count(*) FILTER (WHERE v->>'pad' = repeat(md5(id::text), {REPEAT})) FROM {T};",
         'IIII', a),
        # Three scans of the table at once.
        (f"SELECT count(*), sum(id) FROM (SELECT id, v FROM {T} UNION ALL "
         f"SELECT id, v FROM {T} WHERE id % 2 = 0 UNION ALL "
         f"SELECT id, v FROM {T} WHERE id % 3 = 0) s WHERE length(v->>'pad') > 0;",
         'II', b),
        # Both sides of the join scan the wide rows.
        (f"SELECT count(*), sum(a.id) FROM {T} a JOIN {T} b ON a.id = b.id + 1 "
         f"WHERE a.v->>'pad' <> b.v->>'pad';",
         'II', c),
        # An ordered scan keeps the order of the table whatever the variables.
        (f"SELECT id FROM {T} ORDER BY id LIMIT 3;", 'I', d),
    ]


def emit_queries(out, rows):
    for sql, types, expected in queries(rows):
        out.append(f"query {types}\n{sql}\n----")
        for row in expected:
            out.append(' '.join(str(x) for x in row))
        out.append('')


def emit_variants(out, rows):
    for mode in ['distributed', 'local']:
        out.append(f"statement ok\nSET QUERY_MODE TO {mode};\n")
        for name, settings in VARIANTS:
            out.append(f"# {mode}: {name}.")
            for var, value in DEFAULTS:
                out.append(f"statement ok\nSET {var} = {value};\n")
            for var, value in settings:
                out.append(f"statement ok\nSET {var} = {value};\n")
            emit_queries(out, rows)
    for var, value in DEFAULTS:
        out.append(f"statement ok\nSET {var} = {value};\n")
    out.append("statement ok\nSET QUERY_MODE TO auto;\n")


def main(path):
    rows = {i: md5(i) * REPEAT for i in range(1, N + 1)}
    out = [
        "# Generated by e2e_test/batch/scan_read_memory.gen.py: do not edit by hand.",
        "# The memory of the storage reads of batch scans: wide rows, several scans at once,",
        "# each scan variable off and on. The results must not change.",
        "",
        "statement ok\nSET RW_IMPLICIT_FLUSH TO true;\n",
        "query TTTT\nSELECT current_setting('batch_scan_max_open_vnode_iterators'), "
        "current_setting('batch_scan_prefetch_budget_mb'), "
        "current_setting('batch_scan_prefetch_within_query_limit'), "
        "current_setting('batch_scan_release_prefetch_after_ms');\n----\n0 0 false 0\n",
        f"statement ok\nCREATE TABLE {T} (id INT PRIMARY KEY, v JSONB);\n",
        f"statement ok\nINSERT INTO {T} SELECT i, jsonb_build_object('id', i, 'pad', "
        f"repeat(md5(i::text), {REPEAT})) FROM generate_series(1, {N}) i;\n",
        "statement ok\nFLUSH;\n",
    ]
    emit_variants(out, rows)

    # Deletes and updates: the iterators skip the deleted and the replaced versions.
    out.append("# After deletes and updates.")
    out.append(f"statement ok\nDELETE FROM {T} WHERE id % 5 = 0;\n")
    out.append(f"statement ok\nUPDATE {T} SET v = jsonb_build_object('id', id, 'pad', "
               f"repeat(md5((id + 1)::text), 45)) WHERE id % 7 = 0;\n")
    out.append("statement ok\nFLUSH;\n")
    for i in list(rows):
        if i % 5 == 0:
            del rows[i]
    for i in rows:
        if i % 7 == 0:
            rows[i] = md5(i + 1) * 45
    emit_variants(out, rows)

    out.append(f"statement ok\nDROP TABLE {T};\n")
    with open(path, 'w') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
