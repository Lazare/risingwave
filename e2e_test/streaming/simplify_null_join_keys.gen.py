"""Generates `e2e_test/streaming/simplify_null_join_keys.slt`, the differential test of
`streaming_simplify_null_join_keys` (rule `NullKeyJoinRule`: a join whose condition compares with
`=` a column known to be NULL matches nothing): every query is materialized with and without the
variable, and both materialized views must hold the same rows, with the same multiplicities, as
the batch query, after the backfill and after each round of changes.

Usage: python3 e2e_test/streaming/simplify_null_join_keys.gen.py e2e_test/streaming/simplify_null_join_keys.slt
"""
import sys

A, B, C, E, N, V = 'snk_a', 'snk_b', 'snk_c', 'snk_e', 'snk_n', 'snk_v'
VAR = 'streaming_simplify_null_join_keys'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule.
    ('inner_right', 'id, label',
     f"select a.id, b.label from {A} a join {B} b on a.bk = b.k where b.k is null"),
    ('inner_left', 'id, label',
     f"select a.id, b.label from {A} a join {B} b on a.bk = b.k where a.bk is null"),
    ('view', 'id, x, b_k, label',
     f"select * from {V} where b_k is null"),
    ('cast', 'id, v',
     f"select a.id, c.v from {A} a join {C} c on a.bk = c.kb where a.bk is null"),
    ('count_inner', 'n, s',
     f"select count(*) as n, coalesce(sum(a.x), 0) as s from {A} a join {B} b on a.bk = b.k "
     f"where b.k is null"),
    ('left_right_null', 'id, x, label',
     f"select a.id, a.x, b.label from {A} a left join (select * from {B} where k is null) b on a.bk = b.k"),
    ('right_left_null', 'x, id, label',
     f"select a.x, b.id, b.label from (select * from {A} where bk is null) a right join {B} b on a.bk = b.k"),
    ('semi_right', 'id',
     f"select a.id from {A} a where a.bk in (select k from {B} where k is null)"),
    ('anti_right', 'id',
     f"select a.id from {A} a where not exists (select 1 from {B} b where b.k = a.bk and b.k is null)"),
    ('only_one', 'id, label, v',
     f"select a.id, b.label, c.v from {A} a left join (select * from {B} where k is null) b on a.bk = b.k "
     f"join {C} c on a.id = c.id"),
    ('duplicates', 'v, label',
     f"select n.v, b.label from {N} n left join (select * from {B} where k is null) b on n.k = b.k"),
    ('group_over_left', 'v, n, m',
     f"select n.v, count(*) as n, count(b.id) as m from {N} n left join (select * from {B} where k is null) b "
     f"on n.k = b.k group by n.v"),
    # Left as they are by the rule.
    ('kept_indf', 'id, label',
     f"select a.id, b.label from {A} a join {B} b on a.bk is not distinct from b.k where b.k is null"),
    ('kept_full', 'id, label',
     f"select a.id, b.label from {A} a full join (select * from {B} where k is null) b on a.bk = b.k"),
    ('kept_label', 'id, label',
     f"select a.id, b.label from {A} a join {B} b on a.bk = b.k where b.label is null"),
    ('kept_mapping', 'id, p',
     f"select a.id, e.p from {A} a join {E} e on a.bk = e.w where e.u is null"),
    ('kept_anti_pattern', 'id',
     f"select a.id from {A} a left join {B} b on a.bk = b.k where b.k is null"),
    ('kept_preserved', 'id, label',
     f"select a.id, b.label from (select * from {A} where bk is null) a left join {B} b on a.bk = b.k"),
    ('kept_coalesce', 'id, label',
     f"select a.id, b.label from {A} a join {B} b on coalesce(a.bk, 0) = b.k where a.bk is null"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as snk_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"snk_{name}_on", f"snk_{name}_off", cols)
        same_rows(f"snk_{name}_on", f"({sql}) q", cols)


out.append("""# Differential test of `streaming_simplify_null_join_keys`: every query is materialized twice,
# with and without the variable, and both materialized views must hold the rows of the batch query,
# with the same multiplicities, after the backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/simplify_null_join_keys.gen.py <this file>`: edit the
# list of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {A} (id int primary key, bk int, x int)")
stmt(f"create table {B} (id int primary key, k int, label varchar)")
stmt(f"create table {C} (id int primary key, kb bigint, v int)")
stmt(f"create table {E} (p int primary key, u int, w int)")
stmt(f"create table {N} (k int, v int)")
stmt(f"create view {V} as select a.id, a.x, b.k as b_k, b.label from {A} a join {B} b on a.bk = b.k")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {A} values (1, 1, 5), (2, 1, 0), (3, null, 2), (4, null, null), (5, 2, 7), "
     f"(6, 0, 3), (7, 9, 1), (8, null, 9)")
stmt(f"insert into {B} values (1, 1, 'one'), (2, 1, 'uno'), (3, null, 'nk'), (4, null, null), "
     f"(5, 0, 'zero'), (6, 2, null), (7, null, 'nk2')")
stmt(f"insert into {C} values (1, 1, 10), (2, null, 20), (3, 0, 30), (5, 2, 50), (8, null, 80)")
stmt(f"insert into {E} values (1, null, 1), (2, null, 2), (3, 5, 1), (4, null, null), (5, 7, 0)")
stmt(f"insert into {N} values (1, 1), (1, 1), (null, 2), (null, 2), (0, 3), (null, null), (2, 4)")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view snk_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', "select count(*) from snk_left_right_null_on where label is not null", ["0"])
query('I', "select count(*) from snk_anti_right_on", ["8"])
query('II', "select n, s from snk_count_inner_on", ["0 0"])
query('I', "select count(*) from snk_kept_coalesce_on", ["3"])

out.append("# First round of changes: new rows, NULL keys and duplicates on both sides.\n")
stmt(f"insert into {A} values (9, null, 4), (10, 2, 2), (11, 0, 6)")
stmt(f"insert into {B} values (8, 9, 'nine'), (9, null, 'nk3'), (10, 0, 'zero2')")
stmt(f"insert into {C} values (9, null, 90), (10, 2, 100)")
stmt(f"insert into {E} values (6, null, 9), (7, null, 2)")
stmt(f"insert into {N} values (null, 5), (9, 6), (1, 1)")
out.append("# A row written again with an existing primary key replaces the previous one.\n")
stmt(f"insert into {A} values (1, null, 5)")
stmt(f"insert into {B} values (1, null, 'one')")
compare_all("After the inserts")

out.append("# Second round of changes: keys set to NULL and back, deletes (retractions).\n")
stmt(f"update {A} set bk = 0 where id in (3, 4)")
stmt(f"update {A} set bk = null where id in (5, 6)")
stmt(f"update {B} set k = 2 where id = 3")
stmt(f"update {B} set k = null where id in (5, 8)")
stmt(f"update {B} set label = 'changed' where k is null")
stmt(f"delete from {B} where id in (2, 4)")
stmt(f"delete from {A} where id = 2")
stmt(f"update {E} set u = 1 where p = 1")
stmt(f"delete from {N} where k is null and v = 2")
compare_all("After the updates and deletes")

out.append("# Third round of changes: the right side emptied, then filled again; the left side emptied.\n")
stmt(f"delete from {B}")
compare_all("After the right side is emptied")
stmt(f"insert into {B} values (1, 1, 'one'), (2, null, 'nk'), (3, 0, 'zero'), (4, null, 'nk4')")
compare_all("After the right side is filled again")
stmt(f"delete from {A}")
stmt(f"delete from {N}")
compare_all("After the left side is emptied")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view snk_{name}_{sfx}")
stmt(f"drop view {V}")
for table in (N, E, C, B, A):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
