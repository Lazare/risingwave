"""Generates `e2e_test/streaming/narrow_value_group_ops.slt`, the differential test of
`streaming_narrow_value_aggregates` through the operators that pass their rows through (rule
`NarrowValuePushRule` below a top-n per group or not, a deduplication, a window): every query is
materialized with and without the variable, and both materialized views must hold the same rows,
with the same multiplicities, as the batch query, after the backfill and after each round of
changes (inserts, updates, deletes). The order keys are unique within each group (and across the
branches of the union), so that every query has one result.

Usage: python3 e2e_test/streaming/narrow_value_group_ops.gen.py e2e_test/streaming/narrow_value_group_ops.slt
"""
import sys

VAR = 'streaming_narrow_value_aggregates'
P = 'nvg'

TABLES = [
    f"create table {P}_ea (id int primary key, k int, ts bigint, doc jsonb)",
    f"create table {P}_eb (id int primary key, k int, ts bigint, doc jsonb)",
    f"create table {P}_d (u int primary key, state varchar, w int)",
]
VIEWS = [
    (f"{P}_va", f"select k, last_value(doc order by ts) as doc, max(ts) as ts from {P}_ea group by k"),
    (f"{P}_vb", f"select k, last_value(doc order by ts) as doc, max(ts) as ts from {P}_eb group by k"),
    (f"{P}_vab", f"select * from {P}_va union all select * from {P}_vb"),
    (f"{P}_vu", f"select distinct on (k) * from {P}_vab order by k, ts desc"),
]

# (name, columns of the result, query)
CASES = [
    ('join_topn_union', 'u int, x varchar',
     f"select d.u, vu.doc->'a'->>'b' as x from {P}_vu vu join {P}_d d on vu.k = d.u "
     f"where d.state = 'open'"),
    ('fields', 'k int, c varchar, b varchar, n int',
     f"select k, doc->>'c' as c, doc->'a'->>'b' as b, (doc->>'n')::int as n from {P}_vu"),
    ('ordered_by_field', 'k int, c varchar',
     f"select distinct on (k) k, doc->>'c' as c from {P}_vab order by k, doc->>'o', ts"),
    ('top_n', 'k int, c varchar',
     f"select k, doc->>'c' as c from {P}_vab order by ts desc limit 3"),
    ('dedup', 'k int, c varchar',
     f"select distinct on (k) k, doc->>'c' as c from {P}_va"),
    ('window_rn', 'k int, c varchar',
     f"select k, c from (select k, doc->>'c' as c, "
     f"row_number() over (partition by k order by ts desc) as rn from {P}_vab) s where rn = 1"),
    ('window_count', 'k int, c varchar, n bigint',
     f"select k, doc->>'c' as c, count(*) over (partition by k) as n from {P}_vab"),
    # Left as they are.
    ('window_reads_value', 'k int, c varchar, f varchar',
     f"select k, doc->>'c' as c, first_value(doc) over (partition by k order by ts) ->> 'c' as f "
     f"from {P}_vab"),
]

out = []


def comment(text):
    out.append("\n".join(line.strip() for line in text.strip("\n").split("\n")) + "\n")


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    c = ', '.join(col.split()[0] for col in cols.split(', '))
    grouped = lambda t: f"select {c}, count(*) as {P}_rows from {t} group by {c}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"{P}_{name}_on", f"{P}_{name}_off", cols)
        same_rows(f"{P}_{name}_on", f"({sql}) q", cols)


comment("""# Differential test of `streaming_narrow_value_aggregates` through the operators that pass their
# rows through: every query is materialized twice, with and without the variable, and both
# materialized views must hold the rows of the batch query, with the same multiplicities, after the
# backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/narrow_value_group_ops.gen.py <this file>`: edit the
# queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
for sql in TABLES:
    stmt(sql)
for name, sql in VIEWS:
    stmt(f"create view {name} as {sql}")

comment("""# The first rows, present before the queries run (the backfill): several rows per key, a NULL
# key, keys only in one of the event tables, a NULL value, fields that a cast can not read in rows
# that are not the last ones. The order keys `ts` are unique over both event tables.
""")
stmt(f"""insert into {P}_ea values
  (1, 1, 1, '{{"a": {{"b": "b1"}}, "c": "c1", "n": "x", "o": "2"}}'),
  (2, 1, 5, '{{"a": {{"b": "b2"}}, "c": "c2", "n": "2", "o": "1"}}'),
  (3, 2, 2, '{{"c": "c3", "n": "3", "o": "1"}}'),
  (4, 2, 7, null),
  (5, 3, 3, '{{"a": {{"b": "b5"}}, "c": "c5", "n": "5"}}'),
  (6, 4, 4, '{{"a": "flat", "c": "c6", "n": "6", "o": "3"}}'),
  (7, 4, 9, '{{"a": {{"b": "b7"}}, "c": "c7", "n": "7", "o": "0"}}'),
  (8, null, 6, '{{"c": "cnull", "n": "8"}}'),
  (9, 6, 8, '{{"a": {{"b": "b9"}}, "c": "c9", "n": "9"}}')""")
stmt(f"""insert into {P}_eb values
  (1, 1, 11, '{{"a": {{"b": "e1"}}, "c": "d1", "n": "11", "o": "0"}}'),
  (2, 2, 0, '{{"a": {{"b": "e2"}}, "c": "d2", "n": "bad"}}'),
  (3, 5, 12, '{{"a": {{"b": "e3"}}, "c": "d3", "n": "13", "o": "5"}}'),
  (4, 5, 10, '{{"c": "d4", "n": "14"}}'),
  (5, null, 13, '{{"c": "dnull"}}')""")
stmt(f"""insert into {P}_d values
  (1, 'open', 10), (2, 'open', 1), (3, 'closed', 30), (4, 'open', 40), (5, 'open', 50),
  (7, 'open', 70), (8, null, 80)""")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view {P}_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('IT', f"select u, x from {P}_join_topn_union_on order by u", ["1 e1", "2 NULL", "4 b7", "5 e3"])
query('IT', f"select k, n from {P}_fields_on order by k", ["1 11", "2 NULL", "3 5", "4 7", "5 13", "6 9", "NULL NULL"])

comment("""# First round of changes: new last rows (a new value of a top-n row), a new key in both
# event tables, states of the other side changed.
""")
stmt(f"""insert into {P}_ea values
  (10, 1, 14, '{{"a": {{"b": "b10"}}, "c": "c10", "n": "10", "o": "4"}}'),
  (11, 7, 15, '{{"c": "c11", "n": "11"}}')""")
stmt(f"insert into {P}_eb values (6, 7, 16, '{{\"a\": {{\"b\": \"e6\"}}, \"c\": \"d6\", \"n\": \"16\"}}')")
stmt(f"update {P}_d set state = 'open' where u = 3")
stmt(f"update {P}_d set state = 'closed' where u = 1")
compare_all("After the inserts and updates")

comment("""# Second round of changes: last rows deleted (the previous row becomes the result again),
# values updated (also to NULL) without a change of the order keys, a key moved.
""")
stmt(f"delete from {P}_ea where id in (10, 7)")
stmt(f"update {P}_eb set doc = null where id = 3")
stmt(f"update {P}_ea set doc = '{{\"a\": {{\"b\": \"b5u\"}}, \"c\": \"c5u\", \"n\": \"55\"}}' where id = 5")
stmt(f"update {P}_ea set k = 3 where id = 9")
stmt(f"delete from {P}_d where u in (2, 5)")
compare_all("After the updates and deletes")

out.append("# Third round of changes: one event table emptied, then filled again.\n")
stmt(f"delete from {P}_eb")
compare_all("After a table is emptied")
stmt(f"""insert into {P}_eb values
  (7, 1, 20, '{{"a": {{"b": "e7"}}, "c": "d7", "n": "20"}}'), (8, 3, 21, '{{"c": "d8"}}')""")
compare_all("After the table is filled again")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view {P}_{name}_{sfx}")
for name, _ in reversed(VIEWS):
    stmt(f"drop view {name}")
for sql in reversed(TABLES):
    stmt(f"drop table {sql.split()[2]}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
