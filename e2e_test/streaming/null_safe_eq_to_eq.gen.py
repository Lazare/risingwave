"""Generates `e2e_test/streaming/null_safe_eq_to_eq.slt`, the differential test of
`streaming_null_safe_eq_to_eq` (rule `NullSafeEqToEqRule`: `a IS NOT DISTINCT FROM b` becomes
`a = b` in a join condition, a filter or a scan predicate when `a` or `b` is never NULL): every
query is materialized with and without the variable, and both materialized views must hold the
same rows, with the same multiplicities, as the batch query, after the backfill and after each
round of changes.

Usage: python3 e2e_test/streaming/null_safe_eq_to_eq.gen.py e2e_test/streaming/null_safe_eq_to_eq.slt
"""
import sys

A, B, N = 'sne_a', 'sne_b', 'sne_n'
VAR = 'streaming_null_safe_eq_to_eq'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule. A primary key column is not proven non-null: RisingWave does not
    # declare it NOT NULL.
    ('join_not_null', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.x is not distinct from b.k"),
    ('filter_constant', 'id, k, y',
     f"select id, k, y from {B} where k is not distinct from 5"),
    ('join_is_not_null', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.y is not distinct from b.y where b.y is not null"),
    ('other_conjunct', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.y = b.id and a.y is not distinct from b.k"),
    ('left_join', 'id, bid, y',
     f"select a.id, b.id as bid, b.y from {A} a left join {B} b on a.x is not distinct from b.k"),
    ('full_join', 'id, bid, y',
     f"select a.id, b.id as bid, b.y from {A} a full join {B} b on a.x is not distinct from b.k"),
    ('filter_over_left', 'id, y',
     f"select a.id, b.y from {A} a left join {B} b on a.id = b.id where a.x is not distinct from b.k"),
    ('exists_domain', 'id',
     f"select a.id from {A} a where exists (select 1 from {B} b where b.k = a.id limit 1)"),
    ('not_exists_domain', 'id',
     f"select a.id from {A} a where not exists (select 1 from {B} b where b.k = a.id limit 1)"),
    ('scalar_domain', 'id, m',
     f"select a.id, (select max(b.y) from {B} b where b.k = a.x) as m from {A} a"),
    ('duplicates_left', 'v, id',
     f"select n.v, a.id from {N} n left join {A} a on a.id is not distinct from n.k"),
    ('duplicates_semi', 'k, v',
     f"select n.k, n.v from {N} n where exists (select 1 from {A} a where a.x = n.k limit 1)"),
    ('duplicates_anti', 'k, v',
     f"select n.k, n.v from {N} n where not exists (select 1 from {A} a where a.x = n.k limit 1)"),
    ('count_per_key', 'id, n',
     f"select a.id, count(b.id) as n from {A} a left join {B} b on a.x is not distinct from b.k group by a.id"),
    # Left as they are by the rule.
    ('kept_join_pk', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.id is not distinct from b.k"),
    ('kept_left_pk', 'id, y',
     f"select a.id, b.y from {A} a left join {B} b on a.id is not distinct from b.k"),
    ('kept_nullable', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.y is not distinct from b.y"),
    ('kept_or', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.id = b.id and ((a.x is not distinct from b.k) or b.y > 0)"),
    ('kept_not', 'id, y',
     f"select a.id, b.y from {A} a join {B} b on a.id = b.id and not (a.x is not distinct from b.k)"),
    ('kept_project', 'id, same',
     f"select a.id, a.x is not distinct from b.k as same from {A} a join {B} b on a.id = b.id"),
    ('kept_filter_over_left', 'id, y',
     f"select a.id, b.y from {A} a left join {B} b on a.id = b.id where a.y is not distinct from b.k"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as sne_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"sne_{name}_on", f"sne_{name}_off", cols)
        same_rows(f"sne_{name}_on", f"({sql}) q", cols)


out.append("""# Differential test of `streaming_null_safe_eq_to_eq`: every query is materialized twice, with
# and without the variable, and both materialized views must hold the rows of the batch query,
# with the same multiplicities, after the backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/null_safe_eq_to_eq.gen.py <this file>`: edit the list
# of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {A} (id int primary key, k int, x int not null, y int)")
stmt(f"create table {B} (id int primary key, k int, y int, kb bigint)")
stmt(f"create table {N} (k int, v int)")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {A} values (1, 1, 1, 1), (2, null, 2, null), (3, 3, 5, 3), (4, null, 4, null), "
     f"(5, 5, 5, 7), (6, 0, 0, null)")
stmt(f"insert into {B} values (1, 1, 1, 1), (2, null, null, null), (3, 5, 3, 5), (4, null, 7, 4), "
     f"(5, 2, null, 2), (6, 5, 5, null), (7, 9, 0, 9), (8, null, null, 8)")
stmt(f"insert into {N} values (1, 1), (1, 1), (null, 2), (null, 2), (5, 3), (null, null), (9, 4), (0, 5)")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view sne_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', "select count(*) from sne_full_join_on where id is null", ["4"])
query('I', "select count(*) from sne_duplicates_anti_on where k is null", ["3"])

out.append("# First round of changes: new rows, NULLs and duplicates on both sides.\n")
stmt(f"insert into {A} values (7, 2, 9, 2), (8, null, 8, 5)")
stmt(f"insert into {B} values (9, 7, 2, 7), (10, null, 5, null), (11, 8, null, 1)")
stmt(f"insert into {N} values (null, 6), (2, 7), (5, 3)")
out.append("# A row written again with an existing primary key replaces the previous one.\n")
stmt(f"insert into {A} values (1, null, 1, null)")
stmt(f"insert into {B} values (1, null, 1, 1)")
compare_all("After the inserts")

out.append("# Second round of changes: values set to NULL and back, deletes (retractions).\n")
stmt(f"update {A} set y = null where id in (1, 3)")
stmt(f"update {A} set y = 4, k = 4 where id in (2, 4)")
stmt(f"update {A} set x = 9 where id = 6")
stmt(f"update {B} set k = null where id in (3, 7)")
stmt(f"update {B} set k = 4, y = 4 where id in (2, 8)")
stmt(f"delete from {B} where id in (5, 6)")
stmt(f"delete from {A} where id = 5")
stmt(f"delete from {N} where k is null and v = 2")
compare_all("After the updates and deletes")

out.append("# Third round of changes: only NULLs in the compared columns of the right side, then the\n"
           "# right side emptied and filled again, then the left side emptied.\n")
stmt(f"update {B} set k = null, y = null")
compare_all("After the right side holds only NULLs")
stmt(f"delete from {B}")
compare_all("After the right side is emptied")
stmt(f"insert into {B} values (1, 1, 1, 1), (2, null, null, null), (3, 0, 0, 0), (4, 9, 9, 9)")
compare_all("After the right side is filled again")
stmt(f"delete from {A}")
stmt(f"delete from {N}")
compare_all("After the left side is emptied")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view sne_{name}_{sfx}")
for table in (N, B, A):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
