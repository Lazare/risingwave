"""Generates `e2e_test/streaming/simplify_exists_subquery.slt`, the differential test of
`streaming_simplify_exists_subquery` (rule `ExistsSubquerySimplifyRule`: the limit, `DISTINCT` and
`GROUP BY` without aggregates that can not change the result of a correlated `EXISTS` / `IN`
subquery are removed before unnesting): every query is materialized with and without the
variable, and both materialized views must hold the same rows, with the same multiplicities, as
the batch query, after the backfill and after each round of changes.

Usage: python3 e2e_test/streaming/simplify_exists_subquery.gen.py e2e_test/streaming/simplify_exists_subquery.slt
"""
import sys

T, U, N = 'sse_t', 'sse_u', 'sse_n'
VAR = 'streaming_simplify_exists_subquery'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule.
    ('exists_topn', 'id',
     f"select t.id from {T} t where exists (select 1 from {U} u where u.k = t.k order by u.ts desc limit 1)"),
    ('exists_limit', 'id',
     f"select t.id from {T} t where exists (select u.v from {U} u where u.k = t.k limit 3)"),
    ('not_exists_limit', 'id',
     f"select t.id from {T} t where not exists (select 1 from {U} u where u.k = t.k limit 1)"),
    ('exists_distinct', 'id',
     f"select t.id from {T} t where exists (select distinct u.v from {U} u where u.k = t.k)"),
    ('exists_group_by', 'id',
     f"select t.id from {T} t where exists (select u.v from {U} u where u.k = t.k group by u.v)"),
    ('in_distinct', 'id',
     f"select t.id from {T} t where t.y in (select distinct u.v from {U} u where u.k = t.k)"),
    ('not_in_distinct', 'id',
     f"select t.id from {T} t where t.y not in (select distinct u.v from {U} u where u.k = t.k)"),
    ('exists_distinct_limit', 'id',
     f"select t.id from {T} t where exists (select distinct s.v from "
     f"(select u.v from {U} u where u.k = t.k limit 2) s)"),
    ('exists_ties', 'id',
     f"select t.id from {T} t where exists (select 1 from {U} u where u.k = t.k order by u.ts "
     f"fetch first 1 rows with ties)"),
    ('exists_non_equi', 'id',
     f"select t.id from {T} t where exists (select 1 from {U} u where u.k = t.k and u.v > t.y limit 1)"),
    ('duplicates_semi', 'k, y',
     f"select n.k, n.y from {N} n where exists (select 1 from {U} u where u.k = n.k limit 1)"),
    ('duplicates_anti', 'k, y',
     f"select n.k, n.y from {N} n where not exists (select 1 from {U} u where u.k = n.k order by u.ts limit 1)"),
    ('duplicates_in', 'k, y',
     f"select n.k, n.y from {N} n where n.y in (select u.v from {U} u where u.k = n.k group by u.v)"),
    ('count_semi', 'c',
     f"select count(*) as c from {T} t where exists (select 1 from {U} u where u.k = t.k limit 1)"),
    # Left as they are by the rule.
    ('kept_offset', 'id',
     f"select t.id from {T} t where exists (select 1 from {U} u where u.k = t.k order by u.ts, u.id "
     f"limit 1 offset 1)"),
    ('kept_having', 'id',
     f"select t.id from {T} t where exists (select u.v from {U} u where u.k = t.k group by u.v "
     f"having count(*) > 1)"),
    ('kept_in_limit', 'id',
     f"select t.id from {T} t where t.y in (select u.v from {U} u where u.k = t.k order by u.ts, u.id limit 1)"),
    ('kept_filter_over_limit', 'id',
     f"select t.id from {T} t where exists (select 1 from (select u.v from {U} u where u.k = t.k "
     f"order by u.ts desc, u.id limit 1) s where s.v > 0)"),
    ('kept_set_returning', 'id',
     f"select t.id from {T} t where exists (select unnest(array[u.v, u.ts]) from {U} u where u.k = t.k limit 1)"),
    ('kept_select_list', 'id, e',
     f"select t.id, exists (select 1 from {U} u where u.k = t.k limit 1) as e from {T} t"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as sse_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"sse_{name}_on", f"sse_{name}_off", cols)
        same_rows(f"sse_{name}_on", f"({sql}) q", cols)


out.append("""# Differential test of `streaming_simplify_exists_subquery`: every query is materialized twice,
# with and without the variable, and both materialized views must hold the rows of the batch query,
# with the same multiplicities, after the backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/simplify_exists_subquery.gen.py <this file>`: edit the
# list of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {T} (id int primary key, k int, x int not null, y int)")
stmt(f"create table {U} (id int primary key, k int, ts int, v int)")
stmt(f"create table {N} (k int, y int)")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {T} values (1, 1, 1, 10), (2, 2, 2, 20), (3, null, 3, 10), (4, 4, 4, null), "
     f"(5, 1, 5, 11), (6, 9, 6, 0)")
stmt(f"insert into {U} values (1, 1, 5, 10), (2, 1, 5, 11), (3, 1, 7, null), (4, 2, 1, 20), "
     f"(5, null, 2, 10), (6, 4, 3, 1), (7, 4, 3, 1), (8, 2, 9, -1)")
stmt(f"insert into {N} values (1, 10), (1, 10), (null, 10), (null, null), (2, 21), (4, 1), (4, 1), (7, 0)")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view sse_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', "select count(*) from sse_exists_topn_on", ["4"])
query('I', "select count(*) from sse_duplicates_anti_on", ["3"])

out.append("# First round of changes: new rows, NULL keys, duplicates, ties.\n")
stmt(f"insert into {T} values (7, 7, 7, 70), (8, null, 8, null)")
stmt(f"insert into {U} values (9, 7, 1, 70), (10, 7, 1, 71), (11, 9, 0, 0)")
stmt(f"insert into {N} values (9, 0), (null, 5), (7, 70)")
out.append("# A row written again with an existing primary key replaces the previous one.\n")
stmt(f"insert into {T} values (1, 1, 1, 11)")
stmt(f"insert into {U} values (1, 1, 5, 12)")
compare_all("After the inserts")

out.append("# Second round of changes: keys and values set to NULL and back, deletes (retractions).\n")
stmt(f"update {U} set k = null where id in (4, 8)")
stmt(f"update {U} set k = 2 where id = 5")
stmt(f"update {U} set v = null where id in (6, 9)")
stmt(f"update {U} set ts = 0 where id = 7")
stmt(f"update {T} set k = 4 where id = 3")
stmt(f"update {T} set y = null where id = 2")
stmt(f"delete from {U} where id in (2, 3)")
stmt(f"delete from {T} where id = 6")
stmt(f"delete from {N} where k is null and y = 10")
compare_all("After the updates and deletes")

out.append("# Third round of changes: only NULL keys on the subquery side, then the subquery side\n"
           "# emptied and filled again, then the outer side emptied.\n")
stmt(f"update {U} set k = null")
compare_all("After the subquery side holds only NULL keys")
stmt(f"delete from {U}")
compare_all("After the subquery side is emptied")
stmt(f"insert into {U} values (1, 1, 1, 10), (2, null, 1, 20), (3, 4, 2, null), (4, 7, 1, 70)")
compare_all("After the subquery side is filled again")
stmt(f"delete from {T}")
stmt(f"delete from {N}")
compare_all("After the outer side is emptied")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view sse_{name}_{sfx}")
for table in (N, U, T):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
