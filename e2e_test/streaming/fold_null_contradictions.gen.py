"""Generates `e2e_test/streaming/fold_null_contradictions.slt`, the differential test of
`streaming_fold_null_contradictions` (rule `NullContradictionRule`: a filter, a scan or a join
whose condition holds both `e IS NULL` and a conjunct that can not be true when `e` is NULL
produces nothing): every query is materialized with and without the variable, and both
materialized views must hold the same rows, with the same multiplicities, as the batch query,
after the backfill and after each round of changes.

Usage: python3 e2e_test/streaming/fold_null_contradictions.gen.py e2e_test/streaming/fold_null_contradictions.slt
"""
import sys

T, R, S, W, M = 'sfnc_t', 'sfnc_r', 'sfnc_s', 'sfnc_w', 'sfnc_m'
VAR = 'streaming_fold_null_contradictions'
P = 'sfnc'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule.
    ('coalesce_regexp', 'id',
     f"select id from {T} where coalesce(a, b) is null and coalesce(a, b) ~ '^[a-z]+$'"),
    ('null_key', 'x',
     f"select x from {S} where id is null and id ~ '^[a-z]+$'"),
    ('view_like', 'k, c',
     f"select k, c from {W} where k is null and k like 'x%'"),
    ('coalesce_argument', 'id',
     f"select id from {T} where coalesce(a, b) is null and b = 'x'"),
    ('cast_arithmetic', 'id',
     f"select id from {T} where (c::varchar) is null and length(c::varchar) + 1 > 3"),
    ('jsonb', 'id',
     f"select id from {T} where j->>'k' is null and j->>'k' = 'x'"),
    ('count_join', 'n',
     f"select count(*) as n from {T} t join {R} r on t.a = r.k "
     f"where coalesce(t.a, t.b) is null and upper(coalesce(t.a, t.b)) = 'X'"),
    ('union_branch', 'id, c',
     f"select id, c from {T} where c > 0 union all "
     f"select id, c from {T} where coalesce(c, d) is null and coalesce(c, d) <> 0"),
    ('right_join_empty', 'k, c, id',
     f"select r.k, q.c, q.id from {R} r right join (select id, c, coalesce(a, b) as key from {T}) q "
     f"on r.k = q.key where q.key is null and q.key ~ '^[0-9]+$'"),
    ('left_join_on', 'id, k, rid',
     f"select t.id, r.k, r.id as rid from {T} t left join {R} r "
     f"on coalesce(t.a, t.b) is null and coalesce(t.a, t.b) = r.k"),
    ('anti_join_on', 'id',
     f"select t.id from {T} t where not exists "
     f"(select 1 from {R} r where coalesce(t.a, t.b) is null and coalesce(t.a, t.b) = r.k)"),
    ('agg_over_union', 'c, n',
     f"select c, count(*) as n from (select c from {T} where d > 0 union all "
     f"select c from {T} where c is null and c + d > 1) u group by c"),
    # Left as they are by the rule.
    ('kept_coalesce_constant', 'id',
     f"select id from {T} where a is null and coalesce(a, 'z') = 'z'"),
    ('kept_greatest', 'id',
     f"select id from {T} where c is null and greatest(c, 1) > 0"),
    ('kept_case', 'id',
     f"select id from {T} where c is null and case when c is null then 1 else c end = 1"),
    ('kept_inside_or', 'id',
     f"select id from {T} where (coalesce(a, b) is null and coalesce(a, b) ~ '^x') or d = 1"),
    ('kept_other_expression', 'id',
     f"select id from {T} where coalesce(a, b) is null and coalesce(b, a) ~ '^x'"),
    ('kept_padded_side', 'id, rid',
     f"select t.id, r.id as rid from {T} t left join {R} r on t.id = r.id "
     f"where r.k is null and coalesce(r.k, t.a) = 'x'"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as {P}_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"{P}_{name}_on", f"{P}_{name}_off", cols)
        same_rows(f"{P}_{name}_on", f"({sql}) q", cols)


out.append("""# Differential test of `streaming_fold_null_contradictions`: every query is materialized
# twice, with and without the variable, and both materialized views must hold the rows of the
# batch query, with the same multiplicities, after the backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/fold_null_contradictions.gen.py <this file>`: edit the
# list of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {T} (id int primary key, a varchar, b varchar, c int, d int, j jsonb)")
stmt(f"create table {R} (id int primary key, k varchar, v int)")
stmt(f"create table {S} (id varchar primary key, x int)")
stmt(f"create view {W} as select coalesce(a, b) as k, c, d from {T}")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {T} values (1, 'x', null, 1, 2, '{{\"k\": \"x\"}}'), (2, null, null, null, 1, '{{}}'), "
     f"(3, null, 'x', null, null, null), (4, 'abc', 'X', 12, null, '{{\"k\": null}}'), "
     f"(5, null, null, null, null, '{{\"k\": \"y\"}}'), (6, '42', null, 0, 3, null), (7, 'x', 'x', 1, 1, null)")
stmt(f"insert into {R} values (1, 'x', 1), (2, null, null), (3, 'abc', 12), (4, '42', 0), (5, 'x', null)")
stmt(f"insert into {S} values ('abc', 1), ('42', 2), ('x', 3)")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view {P}_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', f"select count(*) from {P}_left_join_on_on where k is not null", ["0"])
query('I', f"select count(*) from {P}_left_join_on_on", ["7"])
query('I', f"select count(*) from {P}_anti_join_on_on", ["7"])
query('I', f"select count(*) from {P}_kept_coalesce_constant_on", ["3"])

out.append("# First round of changes: new rows, rows written again with an existing primary key.\n")
stmt(f"insert into {T} values (8, null, null, 5, null, '{{\"k\": \"x\"}}'), (1, null, null, null, null, null)")
stmt(f"insert into {R} values (6, null, 5), (1, 'X', 1)")
stmt(f"insert into {S} values ('y', 4)")
compare_all("After the inserts")

out.append("# Second round of changes: values set to NULL and back, deletes (retractions).\n")
stmt(f"update {T} set a = null, b = null where id in (4, 6)")
stmt(f"update {T} set c = 7 where id = 2")
stmt(f"update {T} set a = 'x' where id = 5")
stmt(f"delete from {T} where id = 7")
stmt(f"delete from {R} where id in (2, 3)")
compare_all("After the updates and deletes")

out.append("# Third round of changes: one side emptied, then filled again.\n")
stmt(f"delete from {R}")
compare_all("After the right side is emptied")
stmt(f"insert into {R} values (1, 'x', 1), (2, null, 2)")
stmt(f"delete from {T}")
compare_all("After the left side is emptied")

out.append("""# Watermarks: a filter on a table with a watermark is never replaced with an empty relation, so
# that an `EMIT ON WINDOW CLOSE` job above it can still be planned and runs.
""")
stmt(f"create table {M} (k varchar, ts timestamp, watermark for ts as ts - interval '5 minutes') append only")
stmt(f"set {VAR} = true")
stmt(f"create materialized view {P}_eowc as select window_start, count(*) as n "
     f"from tumble({M}, ts, interval '1' hour) where k is null and k ~ '^x' "
     f"group by window_start emit on window close")
stmt(f"set {VAR} = false")
stmt(f"insert into {M} values ('x', '2026-01-01 00:10:00'), (null, '2026-01-01 00:20:00'), "
     f"('xy', '2026-01-01 03:00:00')")
stmt("flush")
query('I', f"select count(*) from {P}_eowc", ["0"])
stmt(f"drop materialized view {P}_eowc")
stmt(f"drop table {M}")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view {P}_{name}_{sfx}")
stmt(f"drop view {W}")
for table in (S, R, T):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
