"""Generates `e2e_test/streaming/simplify_in_lists_and_coalesce.slt`, the differential test of
`streaming_simplify_in_lists_and_coalesce` (rule `InListCoalesceSimplifyRule`: the conjuncts that
restrict the same expression to lists of constants are intersected, the repeated arguments of
`COALESCE` are removed): every query is materialized with and without the variable, and both
materialized views must hold the same rows, with the same multiplicities, as the batch query,
after the backfill and after each round of changes.

Usage: python3 e2e_test/streaming/simplify_in_lists_and_coalesce.gen.py e2e_test/streaming/simplify_in_lists_and_coalesce.slt
"""
import sys

T, R = 'ssil_t', 'ssil_r'
VAR = 'streaming_simplify_in_lists_and_coalesce'
P = 'ssil'

# (name, columns of the result, query)
CASES = [
    # Rewritten by the rule.
    ('one_common', 'id',
     f"select id from {T} where c in (1, 2) and c in (1, 3, 4)"),
    ('two_common', 'id',
     f"select id from {T} where a in ('x', 'y', 'z') and a in ('w', 'z', 'y')"),
    ('equality', 'id',
     f"select id from {T} where c = 2 and c in (1, 2) and d > 0"),
    ('null_item', 'id',
     f"select id from {T} where c in (1, null) and c in (1, 2)"),
    ('expression', 'id',
     f"select id from {T} where upper(a) in ('X', 'Y') and upper(a) in ('Y', 'Z')"),
    ('empty', 'id',
     f"select id from {T} where upper(a) in ('X', 'Y') and upper(a) in ('Z')"),
    ('empty_join', 'n',
     f"select count(*) as n from {T} t join {R} r on t.c = r.v where t.c in (1, 2) and t.c in (3)"),
    ('join_condition', 'id, k',
     f"select t.id, r.k from {T} t left join {R} r on t.c = r.v and r.k in ('x', 'y') and r.k in ('y', 'z')"),
    ('coalesce_project', 'x, y',
     f"select coalesce(a, a, b, a) as x, coalesce(c, c) as y from {T}"),
    ('coalesce_filter', 'id',
     f"select id from {T} where coalesce(a, b, a, b) = 'x'"),
    ('coalesce_group', 'x, n',
     f"select coalesce(b, b, a) as x, count(*) as n from {T} group by coalesce(b, b, a)"),
    # Left as they are by the rule.
    ('kept_different_columns', 'id',
     f"select id from {T} where c in (1, 2) and d in (2, 3)"),
    ('kept_or', 'id',
     f"select id from {T} where c in (1, 2) or c in (2, 3)"),
    ('kept_numeric', 'id',
     f"select id from {T} where n in (1.0, 2.0) and n in (1.00, 3.0)"),
    ('kept_not_in', 'id',
     f"select id from {T} where c not in (1, 2) and c in (2, 3)"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as {P}_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def compare_all(title):
    out.append(f"# {title}: with and without the rule, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"{P}_{name}_on", f"{P}_{name}_off", cols)
        same_rows(f"{P}_{name}_on", f"({sql}) q", cols)


out.append("""# Differential test of `streaming_simplify_in_lists_and_coalesce`: every query is materialized
# twice, with and without the variable, and both materialized views must hold the rows of the
# batch query, with the same multiplicities, after the backfill and after each round of changes.
#
# Generated by `python3 e2e_test/streaming/simplify_in_lists_and_coalesce.gen.py <this file>`: edit the
# list of queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {T} (id int primary key, a varchar, b varchar, c int, d int, n numeric)")
stmt(f"create table {R} (id int primary key, k varchar, v int)")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {T} values (1, 'x', null, 1, 2, 1.0), (2, null, 'y', 2, 1, 1.00), (3, 'y', 'x', 3, null, 3), "
     f"(4, 'Y', null, null, 3, null), (5, null, null, 1, 0, 2.0), (6, 'z', 'z', 2, 2, 2), (7, 'x', 'x', 4, 1, 1)")
stmt(f"insert into {R} values (1, 'x', 1), (2, 'y', 2), (3, 'z', 3), (4, null, 1), (5, 'y', null)")

for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view {P}_{name}_{sfx} as {sql}")
stmt(f"set {VAR} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', f"select count(*) from {P}_one_common_on", ["2"])
query('I', f"select count(*) from {P}_empty_on", ["0"])

out.append("# First round of changes: new rows, rows written again with an existing primary key.\n")
stmt(f"insert into {T} values (8, 'Z', 'y', 1, 5, 1.000), (1, 'y', 'y', 2, 2, 2.0)")
stmt(f"insert into {R} values (6, 'y', 2), (1, 'z', 1)")
compare_all("After the inserts")

out.append("# Second round of changes: values set to NULL and back, deletes (retractions).\n")
stmt(f"update {T} set c = null, a = null where id in (2, 6)")
stmt(f"update {T} set c = 1 where id = 4")
stmt(f"delete from {T} where id = 7")
stmt(f"delete from {R} where id in (2, 3)")
compare_all("After the updates and deletes")

out.append("# Third round of changes: one side emptied, then filled again.\n")
stmt(f"delete from {R}")
compare_all("After the right side is emptied")
stmt(f"insert into {R} values (1, 'x', 1), (2, null, 2)")
stmt(f"delete from {T}")
compare_all("After the left side is emptied")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view {P}_{name}_{sfx}")
for table in (R, T):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES), 'cases,', sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
