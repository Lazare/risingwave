"""Generates `e2e_test/streaming/preserve_mv_key.slt`, the differential test of
`streaming_preserve_mv_key` (the plan reductions do not change the key of a materialized view: the
operator that gives the view its key is kept, and the view keeps the distribution key it would
have without the reductions): every query is materialized with the reductions, with and without
the variable, and both materialized views must hold the same rows, with the same multiplicities,
as the batch query, after the backfill and after each round of changes. Views over the views
(joins on their key) are compared the same way.

Usage: python3 e2e_test/streaming/preserve_mv_key.gen.py e2e_test/streaming/preserve_mv_key.slt
"""
import sys

E, D, T = 'pmk_e', 'pmk_d', 'pmk_t'
VAR = 'streaming_preserve_mv_key'
REDUCTIONS = ['streaming_simplify_on_unique_key', 'streaming_merge_repeated_lookups']

# (name, columns of the result, query); `{sfx}` is the suffix of the views of the same run.
CASES = [
    # The operator that gives the view its key is kept with the variable.
    ('top1', 'id, payload, v',
     f"select id, payload, v from (select e.id, e.payload, d.v, "
     f"row_number() over (partition by e.id order by d.v, d.id) as rn "
     f"from {E} e left join {D} d on e.ref_id = d.id) s where rn = 1"),
    ('agg', 'id, v, n',
     f"select e.id, max(d.v) as v, count(*) as n from {E} e left join {D} d on e.ref_id = d.id "
     f"group by e.id"),
    ('distinct', 'id, v',
     f"select id, v from (select distinct e.id, d.v from {E} e left join {D} d on e.ref_id = d.id) s "
     f"where v is not null"),
    ('inner_top1', 'id, v',
     f"select id, v from (select e.id, d.v, row_number() over (partition by e.id order by d.v, d.id) as rn "
     f"from {E} e join {D} d on e.ref_id = d.id) s where rn = 1"),
    # The distribution that a join removed by the reductions gave the view is kept.
    ('selfjoin', 'id, payload, v',
     f"select e1.id, e1.payload || '!' as payload, x.v from {E} e1 "
     f"join (select e2.id, d.v from {E} e2 left join {D} d on e2.ref_id = d.id) x on e1.id = x.id"),
    ('selfjoin_hidden', 'payload, v',
     f"select e1.payload || '!' as payload, x.v from {E} e1 "
     f"join (select e2.id, d.v from {E} e2 left join {D} d on e2.ref_id = d.id) x on e1.id = x.id"),
    # Removed in both runs.
    ('scan_top1', 'id, ref_id',
     f"select id, ref_id from (select id, ref_id, row_number() over (partition by id order by ref_id) as rn "
     f"from {E}) s where rn = 1"),
    ('below_join', 'id, v',
     f"select t.id, x.v from {T} t join (select id, v from (select e.id, d.v, "
     f"row_number() over (partition by e.id order by d.v, d.id) as rn "
     f"from {E} e left join {D} d on e.ref_id = d.id) s where rn = 1) x on t.e_id = x.id"),
]

# Views over the views of the same run, joined on their key.
CONSUMERS = [
    ('c_top1', 'id, v', "select t.id, m.v from {T} t join pmk_top1_{sfx} m on t.e_id = m.id"),
    ('c_agg', 'id, n', "select t.id, m.n from {T} t left join pmk_agg_{sfx} m on t.e_id = m.id"),
    ('c_selfjoin', 'id, payload',
     "select t.id, m.payload from {T} t join pmk_selfjoin_{sfx} m on t.e_id = m.id"),
]

out = []


def stmt(sql):
    out.append(f"statement ok\n{sql};\n")


def query(types, sql, rows):
    out.append(f"query {types}\n{sql};\n----\n" + "\n".join(rows) + "\n")


def same_rows(a, b, cols):
    """Both relations hold the same rows, each the same number of times."""
    grouped = lambda t: f"select {cols}, count(*) as pmk_rows from {t} group by {cols}"
    query('III',
          f"select\n  (select count(*) from ({grouped(a)} except {grouped(b)}) x),\n"
          f"  (select count(*) from ({grouped(b)} except {grouped(a)}) y),\n"
          f"  (select count(*) from {a}) - (select count(*) from {b})",
          ["0 0 0"])


def consumer_sql(sql, sfx):
    return sql.format(T=T, sfx=sfx)


def compare_all(title):
    out.append(f"# {title}: with and without the variable, every materialized view holds the rows of "
               f"the batch query.\n")
    for name, cols, sql in CASES:
        same_rows(f"pmk_{name}_on", f"pmk_{name}_off", cols)
        same_rows(f"pmk_{name}_on", f"({sql}) q", cols)
    for name, cols, sql in CONSUMERS:
        same_rows(f"pmk_{name}_on", f"pmk_{name}_off", cols)
        same_rows(f"pmk_{name}_on", f"({consumer_sql(sql, 'on')}) q", cols)


out.append("""# Differential test of `streaming_preserve_mv_key`: every query is materialized twice with the
# plan reductions, with and without the variable, and both materialized views must hold the rows of
# the batch query, with the same multiplicities, after the backfill and after each round of
# changes. Views joined on the key of those views are compared the same way.
#
# Generated by `python3 e2e_test/streaming/preserve_mv_key.gen.py <this file>`: edit the list of
# queries there and regenerate rather than editing by hand.
""")
stmt("SET RW_IMPLICIT_FLUSH TO true")
stmt(f"create table {E} (id int primary key, ref_id int, payload varchar)")
stmt(f"create table {D} (id int primary key, v varchar)")
stmt(f"create table {T} (id int primary key, e_id int, w int)")
out.append("# Rows present before the materialized views are created: they go through the backfill.\n")
stmt(f"insert into {E} values (1, 1, 'a'), (2, 1, 'b'), (3, 2, 'c'), (4, null, 'd'), (5, 9, null), "
     f"(6, 3, 'f'), (7, 3, 'g'), (8, 4, 'h')")
stmt(f"insert into {D} values (1, 'x'), (2, null), (3, 'z'), (4, 'x'), (6, 'w')")
stmt(f"insert into {T} values (1, 1, 10), (2, 1, 20), (3, 2, 30), (4, 5, 40), (5, null, 50), "
     f"(6, 8, 60), (7, 99, 70)")

for r in REDUCTIONS:
    stmt(f"set {r} = true")
for sfx in ('off', 'on'):
    stmt(f"set {VAR} = {'true' if sfx == 'on' else 'false'}")
    for name, _, sql in CASES:
        stmt(f"create materialized view pmk_{name}_{sfx} as {sql}")
    for name, _, sql in CONSUMERS:
        stmt(f"create materialized view pmk_{name}_{sfx} as {consumer_sql(sql, sfx)}")
stmt(f"set {VAR} = false")
for r in REDUCTIONS:
    stmt(f"set {r} = false")

compare_all("After the backfill")

out.append("# Spot checks of the rows themselves.\n")
query('I', "select count(*) from pmk_top1_on", ["8"])
query('II', "select id, n from pmk_agg_on where id = 2", ["2 1"])

out.append("# First round of changes: new rows on both sides.\n")
stmt(f"insert into {E} values (9, 6, 'i'), (10, null, 'j'), (11, 2, 'k')")
stmt(f"insert into {D} values (9, 'nine'), (7, 'seven')")
stmt(f"insert into {T} values (8, 9, 80), (9, 11, 90), (10, 3, 100)")
out.append("# A row written again with an existing primary key replaces the previous one.\n")
stmt(f"insert into {E} values (1, 6, 'a2')")
stmt(f"insert into {D} values (3, 'z2')")
compare_all("After the inserts")

out.append("# Second round of changes: join keys moved (a row of the view is deleted by one actor and\n"
           "# inserted by another), set to NULL and back, deletes on both sides.\n")
stmt(f"update {E} set ref_id = ref_id + 1 where id in (2, 3, 6)")
stmt(f"update {E} set ref_id = null where id = 8")
stmt(f"update {E} set ref_id = 1 where id = 4")
stmt(f"update {D} set v = 'changed' where id in (1, 2)")
stmt(f"delete from {D} where id = 4")
stmt(f"delete from {E} where id = 7")
stmt(f"update {T} set e_id = 3 where id = 1")
compare_all("After the updates and deletes")

out.append("# Third round of changes: the right side emptied, then filled again; the left side emptied.\n")
stmt(f"delete from {D}")
compare_all("After the right side is emptied")
stmt(f"insert into {D} values (1, 'x'), (2, 'y'), (3, null), (7, 'seven')")
compare_all("After the right side is filled again")
stmt(f"delete from {E}")
compare_all("After the left side is emptied")

out.append("# Cleanup.\n")
for sfx in ('on', 'off'):
    for name, _, _ in reversed(CONSUMERS):
        stmt(f"drop materialized view pmk_{name}_{sfx}")
    for name, _, _ in reversed(CASES):
        stmt(f"drop materialized view pmk_{name}_{sfx}")
for table in (T, D, E):
    stmt(f"drop table {table}")

open(sys.argv[1], 'w').write("\n".join(out))
print(len(CASES) + len(CONSUMERS), 'cases,',
      sum(1 for o in out if o.startswith(('statement', 'query'))), 'records')
